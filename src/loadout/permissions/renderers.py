JsonRenderer = Callable[[Rules, dict[str, Any]], dict[str, Any]]
TextRenderer = Callable[[Rules], str]

HEADER_LINES = (
    "Generated by loadout from permissions.toml.",
    "Edits to this file are replaced on the next sync.",
)

PI_SCHEMA = (
    "https://cdn.jsdelivr.net/npm/@gotgenes/"
    "pi-permission-system@23.0.0/schemas/permissions.schema.json"
)

CATEGORIES = ("allow", "deny", "ask")

# The renderers that author `permission.bash["*"]` — the only documents a
# `[shell] default` can reach. Declared once: `extract.CAPABILITIES` says who may
# vote on the key and `emit.py` reports the targets it does not reach, and both
# have to mean the same set. `pi-project` is absent deliberately — manage.py
# emits no catch-all at project scope (ADR 0006), so there is nothing to seed.
CATCH_ALL_RENDERERS = frozenset({"opencode", "pi"})


@dataclass(frozen=True)
class JsonSpec:
    fn: JsonRenderer
    ensure_ascii: bool = False
    # True when the renderer builds its document from scratch rather than
    # writing into the base it is handed. Such a file has exactly one owner, so
    # it cannot compose with another slice — threading through it would silently
    # discard everything rendered before it.
    owns_whole_file: bool = False


@dataclass(frozen=True)
class ValueSpec:
    """A renderer that produces the *value* of one key, not a whole document.

    The composing loop assigns it under the key the preset names, so it never
    sees the rest of the file and cannot depend on running before or after
    another slice. Distinguished at registration rather than by convention: a
    value renderer handed a whole document would do the wrong thing silently.
    """

    fn: Callable[[dict[str, Any]], Any]


@dataclass(frozen=True)
class TextSpec:
    fn: TextRenderer


@dataclass(frozen=True)
class DocumentTextSpec:
    """A renderer that turns one slice's content into a whole text file.

    `TextSpec` renders from `Rules`; this renders from the document a
    `source_slice` supplies. The two cannot be merged: a generated adapter reads
    hooks and knows nothing of permissions, and a renderer handed the wrong one
    of those would produce a plausible file with the wrong content in it.

    Like `TextSpec` it owns its file outright — there is no composing a second
    slice into a JavaScript module, nor into Codex's plugin TOML.
    """

    fn: Callable[[dict[str, Any]], str]


@dataclass(frozen=True)
class DocumentJsonSpec:
    """The JSON counterpart of `DocumentTextSpec`: renders a whole document from
    content rather than from `Rules` — `.mcp.json` has no shell rules or MCP
    policy in it, only server definitions parsed from `mcp.toml`.

    Like `DocumentTextSpec` it owns its file outright.
    """

    fn: Callable[[dict[str, Any]], dict[str, Any]]


@dataclass(frozen=True)
class MergedTomlSpec:
    """A renderer contributing top-level keys to a file loadout does not own.

    Unlike `DocumentTextSpec` this **composes**: several slices write into
    `~/.codex/config.toml`, and applying each on its own would mean the second
    read the first's result — ADR 0001's feedback loop, rebuilt one layer down.
    The composing step unions the declared keys and concatenates the fragments so
    a single application covers every slice.

    `owns` is declared here rather than read off `fn`'s output, because a set
    derived from what is written cannot express a removal (ADR 0017).
    """

    fn: Callable[[Rules, dict[str, Any]], str]
    owns: frozenset[str]


# --------------------------------------------------------------------------
# claude — mcp-permissions.json: PermissionRequest hook policy, fully owned.
# --------------------------------------------------------------------------


def render_claude_mcp(rules: Rules, base: dict[str, Any]) -> dict[str, Any]:
    return {
        "allow": list(rules.mcp_allow),
        "ask": list(rules.mcp_ask),
        "deny": list(rules.mcp_deny),
    }


# --------------------------------------------------------------------------
# pi — pi/permissions.json, fully owned. Last-match-wins, so a pattern set by
# a later category is deleted and reinserted to move it to the end of the map.
# minimatch means `foo *` never matches a bare `foo`, so both forms are emitted.
# --------------------------------------------------------------------------


def pi_patterns(entry: str) -> list[str]:
    return [entry] if is_glob(entry) else [entry, f"{entry} *"]


def pi_mcp_patterns(entry: str) -> list[str]:
    server, tool = mcp_parts(entry)
    patterns = [f"{server}_{tool}", f"{server}:{tool}"]
    if tool == "*":
        patterns += [f"mcp_server_{server}", f"mcp_connect_{server}"]
    return patterns


def render_pi(rules: Rules, base: dict[str, Any]) -> dict[str, Any]:
    ordered = (("allow", "allow"), ("ask", "ask"), ("deny", "deny"))

    bash: dict[str, str] = {"*": rules.catch_all}
    for category, decision in ordered:
        for entry in rules.shell(category):
            for pattern in pi_patterns(entry):
                bash.pop(pattern, None)
                bash[pattern] = decision

    # `[shell] default` governs bash only; MCP policy has its own three lists.
    mcp: dict[str, str] = {"*": MCP_SEED}
    for category, decision in ordered:
        for entry in rules.mcp(category):
            for pattern in pi_mcp_patterns(entry):
                mcp.pop(pattern, None)
                mcp[pattern] = decision

    return {
        "$schema": PI_SCHEMA,
        "permission": {"*": "allow", "bash": bash, "mcp": mcp},
    }


# --------------------------------------------------------------------------
# codex — codex/rules/permissions.rules: fully owned, Starlark-ish text.
# Token-prefix matcher, so glob entries can't be expressed and are skipped.
# --------------------------------------------------------------------------

CODEX_DECISION = {"allow": "allow", "deny": "forbidden", "ask": "prompt"}


def codex_rule(entry: str, decision: str) -> str:
    tokens = ", ".join(json.dumps(t) for t in entry.split())
    return f'prefix_rule(pattern = [{tokens}], decision = "{decision}")'


def render_codex(rules: Rules) -> str:
    lines = [f"# {line}" for line in HEADER_LINES]
    lines += [
        "#",
        "# Read-only commands are allowed; remote-publishing and destructive",
        "# ops are forbidden; `ask` commands prompt. Glob entries are skipped",
        "# (see end of file) — Codex's token matcher can't express them.",
    ]
    skipped: list[str] = []
    for category in CATEGORIES:
        decision = CODEX_DECISION[category]
        entries = rules.shell(category)
        emitted = [e for e in entries if not is_glob(e)]
        skipped += [e for e in entries if is_glob(e)]
        if emitted:
            lines.append("")
            for entry in emitted:
                lines.append(codex_rule(entry, decision))
    if skipped:
        lines.append("")
        lines.append("# Skipped — glob entries Codex's token matcher can't express")
        lines.append("# (these fall through to Codex's normal approval prompt):")
        for entry in skipped:
            lines.append(f"#   {entry}")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------
# codex — codex/mcp-permissions.toml: fully owned, emitted with tomlkit.
# --------------------------------------------------------------------------


def codex_mcp_policy(rules: Rules) -> dict[str, dict[str, str]]:
    """Per-server, per-tool approval modes, keyed `{server: {tool: mode}}`.

    Shared by the standalone policy renderer and the combined one, so the two
    cannot drift into disagreeing about what a rule means.
    """
    decisions: dict[str, str] = {}
    for category, mode in (("allow", "approve"), ("ask", "prompt"), ("deny", "deny")):
        for entry in rules.mcp(category):
            decisions[entry] = mode

    servers: dict[str, dict[str, str]] = {}
    for entry, mode in decisions.items():
        server, tool = mcp_parts(entry)
        servers.setdefault(server, {})[tool] = mode
    return servers


def _codex_policy_block(tools: dict[str, str], block: Any) -> None:
    """Write one server's approval policy into a table the caller owns."""
    wildcard = tools.get("*")
    if wildcard == "deny":
        block["enabled"] = False
    elif wildcard:
        block["default_tools_approval_mode"] = wildcard
    denied = sorted(tool for tool, mode in tools.items() if tool != "*" and mode == "deny")
    if denied:
        block["disabled_tools"] = denied
    approved = sorted(tool for tool, mode in tools.items() if tool != "*" and mode != "deny")
    if approved:
        per_tool = tomlkit.table(is_super_table=True)
        for tool in approved:
            tool_table = tomlkit.table()
            tool_table["approval_mode"] = tools[tool]
            per_tool[tool] = tool_table
        block["tools"] = per_tool


def _codex_definition_block(server: Server, block: Any) -> None:
    """One server's transport: how to reach it and what to pass it.

    Insertion order is not load-bearing here — tomlkit emits a table's scalars
    ahead of its sub-tables however they were assigned, so `env` cannot capture a
    policy key written after it. The text path has no such protection, which is
    why `surgery.concat_documents` hoists preambles itself.
    """
    if is_http(server):
        assert server.url is not None
        block["url"] = server.url
        if server.auth_env_var:
            block["bearer_token_env_var"] = server.auth_env_var
        return
    assert server.command is not None
    block["command"] = server.command
    if server.args:
        block["args"] = list(server.args)
    if server.env:
        variables = tomlkit.table()
        for key in sorted(server.env):
            variables[key] = server.env[key]
        block["env"] = variables


def render_codex_plugins_merged(rules: Rules, content: dict[str, Any]) -> str:
    """Plugins render from their own slice; `rules` is the merged shape, not input.

    Every merged renderer takes the same pair so composition needs no per-renderer
    signature, the way `JsonSpec` already hands every renderer `(rules, base)`.
    """
    return render_codex_plugins(content)


def render_codex_config(rules: Rules, content: dict[str, Any]) -> str:
    """Every `[mcp_servers.<name>]` table: what the server is, and what it may do.

    Codex keys definitions and approval policy off the same table, so rendering
    them from two slices would declare it twice and Codex would refuse to parse
    its own config. They are combined here rather than merged during composition.

    A name may appear in either source alone: a server defined with no policy
    takes Codex's default, and policy for a server defined elsewhere still applies.
    """
    definitions = {name: value for name, value in content.items() if isinstance(value, Server)}
    policy = codex_mcp_policy(rules)

    document = tomlkit.document()
    for line in HEADER_LINES:
        document.add(tomlkit.comment(line))
    names = sorted(set(definitions) | set(policy))
    if not names:
        return tomlkit.dumps(document)

    roots = tomlkit.table(is_super_table=True)
    for name in names:
        block = tomlkit.table()
        server = definitions.get(name)
        if server is not None:
            _codex_definition_block(server, block)
        if name in policy:
            _codex_policy_block(policy[name], block)
        roots[name] = block
    document["mcp_servers"] = roots
    return tomlkit.dumps(document)


def render_codex_mcp(rules: Rules) -> str:
    servers = codex_mcp_policy(rules)

    document = tomlkit.document()
    for line in HEADER_LINES:
        document.add(tomlkit.comment(line))
    if not servers:
        return tomlkit.dumps(document)

    # Super tables emit no header of their own, so `mcp_servers` and `tools` are
    # only ever seen as the [mcp_servers.<name>] / .tools.<name> prefixes.
    roots = tomlkit.table(is_super_table=True)
    for server in sorted(servers):
        block = tomlkit.table()
        _codex_policy_block(servers[server], block)
        roots[server] = block
    document["mcp_servers"] = roots
    return tomlkit.dumps(document)


# --------------------------------------------------------------------------
# claude — claude/settings.json: replace permissions.allow / deny / ask and
# preserve every other key. The base is a parameter, never a read of this
# renderer's own output.
#
# The owned keys come FIRST inside `permissions`, with hand-maintained keys
# such as defaultMode after them, so the object is constructed rather than
# assigned into — assigning would append and change the order.
#
# render_claude and render_claude_project (below, project-scope section)
# share this body; only the emitted key order differs — CATEGORIES here vs
# PROJECT_CATEGORIES there — expressed as data, not as duplicated code.
# --------------------------------------------------------------------------


def claude_pattern(entry: str) -> str:
    # Colon form matches the command with args or bare; a glob entry is kept
    # literal since Claude's matcher already understands `*`.
    return f"Bash({entry})" if is_glob(entry) else f"Bash({entry}:*)"


def _claude_settings(rules: Rules, base: dict[str, Any], order: tuple[str, ...]) -> dict[str, Any]:
    settings = copy.deepcopy(base)
    base_perms: dict[str, Any] = settings.get("permissions", {})

    built: dict[str, Any] = {
        "allow": (
            [claude_pattern(e) for e in rules.allow]
            + [mcp_native(e) for e in rules.mcp_allow]
            + list(rules.claude_extra_allow)
        ),
        "deny": (
            [claude_pattern(e) for e in rules.deny]
            + [mcp_native(e) for e in rules.mcp_deny]
            + list(rules.claude_extra_deny)
        ),
        "ask": ([claude_pattern(e) for e in rules.ask] + [mcp_native(e) for e in rules.mcp_ask]),
    }
    perms: dict[str, Any] = {key: built[key] for key in order}
    for key, value in base_perms.items():
        if key not in perms:
            perms[key] = value

    settings["permissions"] = perms
    return settings


def render_claude(rules: Rules, base: dict[str, Any]) -> dict[str, Any]:
    return _claude_settings(rules, base, CATEGORIES)


# --------------------------------------------------------------------------
# opencode — opencode.json: replace the `permission` key, preserve model /
# provider from the base. Last-match-wins, so deny is emitted after allow.
# A plain prefix emits BOTH `<entry>` and `<entry> *`, because `pwd *` does
# not match a bare `pwd` under OpenCode's matcher. A glob entry is kept literal.
# --------------------------------------------------------------------------


def opencode_patterns(entry: str) -> list[str]:
    return [entry] if is_glob(entry) else [entry, f"{entry} *"]


def render_opencode(rules: Rules, base: dict[str, Any]) -> dict[str, Any]:
    config = copy.deepcopy(base)

    bash: dict[str, str] = {"*": rules.catch_all}
    for category in CATEGORIES:
        for entry in rules.shell(category):
            for pattern in opencode_patterns(entry):
                bash[pattern] = category

    permission: dict[str, Any] = {"bash": bash}
    for category in CATEGORIES:
        for entry in rules.mcp(category):
            server, tool = mcp_parts(entry)
            permission[f"{server}_{tool}"] = category
    for key, value in rules.opencode_extra.items():
        permission[key] = value

    config["permission"] = permission
    return config


# --------------------------------------------------------------------------
# Project-scope variants. These reproduce ~/ac/permissions/manage.py exactly,
# including defects fixed in later, separately-reviewed commits (ADR 0003):
# Codex does not skip globs (still open); Pi's missing bare command form was
# fixed deliberately in Task 8.
# --------------------------------------------------------------------------

PROJECT_CATEGORIES = ("allow", "ask", "deny")

CODEX_PROJECT_DECISION = {"allow": "allow", "ask": "prompt", "deny": "forbidden"}

CODEX_PROJECT_HEADER = (
    "# Generated by loadout from loadout/permissions.toml. "
    "Edits to this file are replaced on the next sync."
)


def render_codex_project(rules: Rules) -> str:
    lines = [CODEX_PROJECT_HEADER]
    for category in PROJECT_CATEGORIES:
        decision = CODEX_PROJECT_DECISION[category]
        for entry in rules.shell(category):
            tokens = ", ".join(json.dumps(token) for token in shlex.split(entry))
            lines.append(f'prefix_rule(pattern = [{tokens}], decision = "{decision}")')
    return "\n".join(lines) + "\n"


def pi_project_patterns(entry: str) -> list[str]:
    """Identical to pi_patterns — Pi's minimatch semantics do not differ by scope.

    Kept as a distinct name so render_pi_project reads clearly, delegating so the
    two can never drift. They differed only while the project variant reproduced
    manage.py's missing bare form, which this milestone fixed.
    """
    return pi_patterns(entry)


def render_claude_project(rules: Rules, base: dict[str, Any]) -> dict[str, Any]:
    # Same body as render_claude (see _claude_settings above); manage.py
    # emits project-scope Claude settings with keys in allow, ask, deny
    # order — matching claude-mcp's order, not the global settings.json
    # renderer's allow, deny, ask.
    return _claude_settings(rules, base, PROJECT_CATEGORIES)


def render_pi_project(rules: Rules, base: dict[str, Any]) -> dict[str, Any]:
    bash: dict[str, str] = {}
    for category in PROJECT_CATEGORIES:
        for entry in rules.shell(category):
            for pattern in pi_project_patterns(entry):
                bash[pattern] = category

    mcp: dict[str, str] = {}
    for category in PROJECT_CATEGORIES:
        for entry in rules.mcp(category):
            for pattern in pi_mcp_patterns(entry):
                mcp[pattern] = category

    return {"permission": {"bash": bash, "mcp": mcp}}


