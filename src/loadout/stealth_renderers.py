CLAUDE_RULE_LISTS = ("allow", "ask", "deny")
DROID_RULE_LISTS = ("commandAllowlist", "commandDenylist", "commandBlocklist")


def render_claude_local(instructions: str, *, import_agents: bool) -> str:
    parts = [HEADER, *(["@AGENTS.md"] if import_agents else []), instructions]
    return "\n\n".join(parts) + "\n"


def _fragment_keys(
    fragment: Mapping[str, Any], reserved: Mapping[str, tuple[str, ...]]
) -> tuple[tuple[JsonPath, Any], ...]:
    keys: list[tuple[JsonPath, Any]] = []
    for key, value in fragment.items():
        if key in reserved and isinstance(value, Mapping):
            keys.extend(
                ((key, inner), item) for inner, item in value.items() if inner not in reserved[key]
            )
        elif key not in reserved:
            keys.append(((key,), value))
    return tuple(keys)


def _non_empty_lists(
    document: Mapping[str, Any], names: tuple[str, ...], prefix: JsonPath
) -> tuple[tuple[JsonPath, tuple[str, ...]], ...]:
    return tuple(((*prefix, name), tuple(document[name])) for name in names if document.get(name))


def claude_owned(rules: Rules, fragment: Mapping[str, Any]) -> OwnedJson:
    permissions = render_claude_project(rules, {})["permissions"]
    return OwnedJson(
        keys=_fragment_keys(fragment, {"permissions": CLAUDE_RULE_LISTS}),
        rules=_non_empty_lists(permissions, CLAUDE_RULE_LISTS, ("permissions",)),
    )


def droid_owned(rules: Rules, fragment: Mapping[str, Any]) -> OwnedJson:
    lists = render_droid(rules, {})
    keys = tuple(
        (path, value)
        for path, value in _fragment_keys(fragment, {})
        if path[0] not in DROID_RULE_LISTS
    )
    return OwnedJson(keys=keys, rules=_non_empty_lists(lists, DROID_RULE_LISTS, ()))


def codex_stealth_notes(rules: Rules, servers: Mapping[str, Server]) -> tuple[str, ...]:
    return tuple(
        f"codex: approval rules for MCP server {name} are not written, because the stealth source "
        "does not define it and a project table would merge into the user's server"
        for name in sorted(set(codex_mcp_policy(rules)) - set(servers))
    )


def render_codex_stealth_config(
    instructions: str | None, rules: Rules, servers: Mapping[str, Server]
) -> tuple[str, tuple[str, ...]]:
    policy = codex_mcp_policy(rules)
    document = tomlkit.document()
    document.add(tomlkit.comment("Generated by loadout from instructions/ and mcp.toml."))
    document.add(tomlkit.comment("Edits to this file are replaced on the next sync."))
    if instructions is not None:
        document["developer_instructions"] = tomlkit.string(instructions, multiline=True)
    if servers:
        roots = tomlkit.table(is_super_table=True)
        for name in sorted(servers):
            block = tomlkit.table()
            stealth_seams.codex_definition_block(servers[name], block)
            if name in policy:
                stealth_seams.codex_policy_block(policy[name], block)
            roots[name] = block
        document["mcp_servers"] = roots
    notes = codex_stealth_notes(rules, servers)
    return tomlkit.dumps(document), notes


def render_opencode_stealth_permission(rules: Rules) -> dict[str, Any]:
    bash: dict[str, str] = {} if rules.default is None else {"*": rules.default}
    for category in ("allow", "deny", "ask"):
        for entry in rules.shell(category):
            for pattern in opencode_patterns(entry):
                bash[pattern] = category
    permission: dict[str, Any] = {"bash": bash}
    for key, category in stealth_seams.opencode_mcp_keys(rules):
        permission[key] = category
    permission.update(rules.opencode_extra)
    return permission


def opencode_owned(
    rules: Rules | None, servers: Mapping[str, Server], instructions: Path | None
) -> OwnedJson:
    keys: list[tuple[JsonPath, Any]] = []
    if rules is not None:
        permission = render_opencode_stealth_permission(rules)
        if permission != {"bash": {}}:
            keys.append((("permission",), permission))
    if servers:
        keys.append((("mcp",), render_opencode_servers(dict(servers))))
    if instructions is not None:
        keys.append((("instructions",), [str(instructions)]))
    return OwnedJson(keys=tuple(keys), rules=())
