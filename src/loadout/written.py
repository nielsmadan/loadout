"""What `sync` last wrote, per destination — ADR 0008's deferred sidecar.

The guard in `sync.py` asks "could loadout have written this file?" and answers
it from two renders: the committed source and the working tree now. ADR 0008 accepted
that as "correct, at the cost of warning benignly on first adoption and on a
reverted-but-already-synced edit", and deferred a record of what was actually written
until orphan removal forced it.

The cost turned out larger than that estimate. Two cases it does not name: editing a
source twice before committing leaves an output rendered from a state that is neither
baseline, and a skill's supporting file has no accept set at all, so the first edit
blocks every later sync until `--force`. This module supplies the missing third
variant. Retirement is the other consumer, which is why entries are retained until a
destination is retired rather than pruned when a run stops rendering it: a destination
loadout no longer renders is exactly what retirement needs to find.

**It only ever widens acceptance.** Every check is `entry is not None and the hash
matches`, so a missing, corrupt or version-bumped record reproduces the two-variant
behaviour exactly. There is no path where a hand edit is accepted because state was
lost — losing state fails closed.
"""

from __future__ import annotations

import json
import os
import re
import tomllib
from collections.abc import Callable, Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Literal

from .atomic import replace_atomically
from .machine import config_dir
from .output import Merged, entry_path, file_sha256, sha256
from .toml_paths import key_path

VERSION = 1

_BANNER_LINE = re.compile(
    r"^\s*(?:<!--\s*|#\s*|//\s*)generated by loadout\b.*$", re.MULTILINE | re.IGNORECASE
)
_BLANK_RUN = re.compile(r"\n{3,}")
_BANNER_CONTINUATION = re.compile(
    r"^\s*(?:#|//)\s*edits? to this file are replaced.*$"
    r"|^\s*(?:#|//)\s*edit permissions\.toml\b.*$",
    re.MULTILINE | re.IGNORECASE,
)


def normalise(path: Path, content: str) -> str:
    """Key order is load-bearing in output, but not in the question 'who wrote this?'.

    Claude Code rewrites its own settings.json and reorders keys loadout owns; comparing
    the parsed document keeps that from reading as a hand edit.

    The banner comes out for the same reason. It is loadout's own text, so rewording it
    is not evidence a user touched the file — but without this, changing it makes every
    generated file on disk differ from every acceptable variant at once, and the guard
    reports the whole tree as hand-edited. It did, on 205 files.

    Lives here rather than in `sync.py` because the write side and the guard must
    agree on it exactly: a recorded hash is worthless if the two normalise differently.
    """
    if path.suffix != ".json":
        stripped = _BANNER_CONTINUATION.sub("", _BANNER_LINE.sub("", content))
        # Removing the banner leaves the blank line that separated it, so a file
        # with no banner and one with a banner still differ by an interior blank
        # — which `.strip()` cannot reach. Collapsing runs is what makes the two
        # actually compare equal, and without it the guard reports a banner-only
        # difference as a hand edit. It did, on the one skill that carries a
        # `::: opencode` section.
        return _BLANK_RUN.sub("\n\n", stripped).strip()
    try:
        return json.dumps(json.loads(content), sort_keys=True)
    except json.JSONDecodeError:
        return content


@dataclass(frozen=True)
class WrittenEntry:
    """One destination as `sync` left it.

    `norm_sha256` is what the guard compares, because a harness reordering keys in a
    file it shares with loadout is not a hand edit. `sha256` is the raw bytes, which is
    what a copied file is compared by.

    A merged destination carries no hash of the file: the applied document embeds bytes
    the harness owns and may rewrite a second later, so a hash of it would go stale
    without anything having gone wrong. `owned_sha256` hashes each key loadout wrote
    there instead, one by one, `ABSENT` for a key it left out, and `owned` names the
    keys, which retirement strips rather than deleting a file loadout does not own.
    """

    kind: Literal["text", "copied", "merged"]
    sha256: str | None = None
    norm_sha256: str | None = None
    owned: tuple[str, ...] = ()
    owned_sha256: tuple[tuple[str, str], ...] = ()

    @property
    def guarded(self) -> frozenset[str]:
        """The owned keys an edit can touch: those with a hash, or every one when the
        entry predates per-key hashes; an evicted key has none and is stripped whatever
        it holds (review 4, batch 2.1)."""
        hashed = frozenset(key for key, _ in self.owned_sha256)
        return hashed & frozenset(self.owned) if hashed else frozenset(self.owned)


def written_state_path(root: Path, env: Mapping[str, str] | None = None) -> Path:
    """One record per root, named by the root's resolved path.

    Keyed by a hash rather than the path itself so the name is filesystem-safe; the
    path is stored inside the file so it stays inspectable by hand.
    """
    key = sha256(str(root.resolve()).encode())[:16]
    return config_dir(env) / "written" / f"{key}.json"


def read_written(root: Path, env: Mapping[str, str] | None = None) -> dict[Path, WrittenEntry]:
    """The record, or empty when there is none to be had.

    Absent, unreadable, malformed and version-bumped all mean the same thing to the
    caller: no baseline, behave as before the record existed.
    """
    return _entries(_document(written_state_path(root, env)))


def _document(record: Path) -> object:
    try:
        return json.loads(record.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def _entries(document: object) -> dict[Path, WrittenEntry]:
    if not isinstance(document, dict) or document.get("version") != VERSION:
        return {}
    entries = document.get("written")
    if not isinstance(entries, dict):
        return {}
    return {
        Path(name): entry for name, raw in entries.items() if (entry := _entry(raw)) is not None
    }


ENTRY_KINDS = frozenset({"text", "copied", "merged"})


def _entry(raw: object) -> WrittenEntry | None:
    """One recorded destination, or None for a shape no sync writes: an unknown kind was
    once read as a copied file (review 3, batch 4.4). A record only widens what the guard
    accepts, so dropping an entry is the safe reading."""
    if not isinstance(raw, dict) or raw.get("kind") not in ENTRY_KINDS:
        return None
    hashes = (raw.get("sha256"), raw.get("norm_sha256"))
    owned = raw.get("owned", [])
    if not all(value is None or isinstance(value, str) for value in hashes) or not (
        isinstance(owned, list) and all(isinstance(key, str) for key in owned)
    ):
        return None
    return WrittenEntry(
        kind=raw["kind"],
        sha256=hashes[0],
        norm_sha256=hashes[1],
        owned=tuple(owned),
        owned_sha256=_pairs(raw.get("owned_sha256")),
    )


def every_recorded_path(
    within: Iterable[Path],
    env: Mapping[str, str] | None = None,
    *,
    known_root: Path | None = None,
    known: Mapping[Path, WrittenEntry] | None = None,
) -> frozenset[Path]:
    """Every destination inside `within` that any root's record names, so one root never
    mistakes another's output there for a file loadout did not write. Only those names
    become paths: the rest of a record is never scanned. `known` is `known_root`'s record
    already read, which is used rather than read again."""
    prefixes = tuple(f"{folder}{os.sep}" for folder in within)
    if not prefixes:
        return frozenset()
    try:
        records = sorted((config_dir(env) / "written").glob("*.json"))
    except OSError:
        return frozenset()
    paths: set[Path] = set()
    skipped = written_state_path(known_root, env) if known_root is not None else None
    paths.update(path for path in (known or {}) if str(path).startswith(prefixes))
    for record in records:
        if record == skipped:
            continue
        document = _document(record)
        root = _root(document)
        if root is not None and written_state_path(root, env) == record:
            paths.update(Path(name) for name in _names(document) if name.startswith(prefixes))
    return frozenset(paths)


def _names(document: object) -> list[str]:
    """The destinations a record names, by the rule `_entries` reads it with."""
    if not isinstance(document, dict) or document.get("version") != VERSION:
        return []
    entries = document.get("written")
    if not isinstance(entries, dict):
        return []
    return [
        name
        for name, raw in entries.items()
        if isinstance(raw, dict) and isinstance(raw.get("kind"), str)
    ]


def prune_vanished(env: Mapping[str, str] | None = None) -> None:
    """Delete the records of roots that no longer exist.

    Safe for the same reason losing a record is: without one, the guard accepts less
    and retirement touches nothing. A root that cannot be stat'ed for any reason other
    than being absent, such as a sandbox denying it, keeps its record.
    """
    try:
        records = sorted((config_dir(env) / "written").glob("*.json"))
    except OSError:
        return
    for record in records:
        root = _root(_document(record))
        if root is None or not _vanished(root):
            continue
        try:
            record.unlink()
        except OSError:
            continue


def _root(document: object) -> Path | None:
    root = document.get("root") if isinstance(document, dict) else None
    return Path(root) if isinstance(root, str) and Path(root).is_absolute() else None


def _vanished(path: Path) -> bool:
    try:
        path.stat()
    except (FileNotFoundError, NotADirectoryError):
        return True
    except OSError:
        return False
    return False


def record_written(
    root: Path,
    entries: Mapping[Path, WrittenEntry],
    env: Mapping[str, str] | None = None,
    *,
    dropped: Iterable[Path] = (),
) -> Path | None:
    """Merge this run's writes into the record, keeping what earlier runs wrote.

    Retention is the point, not laziness: a destination this run no longer renders is
    precisely what retirement needs to find, and pruning it here would throw that away
    every time a target was deleted. Only `dropped`, what retirement has dealt with,
    leaves the record.
    """
    path = written_state_path(root, env)
    merged = dict(read_written(root, env))
    merged.update(entries)
    for gone in dropped:
        merged.pop(gone, None)
    document: dict[str, Any] = {
        "version": VERSION,
        "root": str(root.resolve()),
        "written": {
            str(dest): {
                k: v
                for k, v in {
                    "kind": entry.kind,
                    "sha256": entry.sha256,
                    "norm_sha256": entry.norm_sha256,
                    "owned": list(entry.owned) or None,
                    "owned_sha256": dict(entry.owned_sha256) or None,
                }.items()
                if v is not None
            }
            for dest, entry in sorted(merged.items(), key=lambda item: str(item[0]))
        },
    }
    try:
        _write_record(path, document)
    except OSError:
        # A record that cannot be written degrades to no record, which is the
        # behaviour that existed before it — never a failed sync. The files are
        # already on disk by the time this runs, so raising here would report a
        # completed sync as broken. A sandbox denying the state directory is the
        # case that forced this: the profile may grant the machine config file
        # without granting the directory beside it.
        return None
    return path


def _write_record(path: Path, document: Mapping[str, Any]) -> None:
    """Written beside the record and renamed over it, so a kill never leaves it torn."""
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(document, indent=2) + "\n"
    replace_atomically(path, lambda handle: handle.write(text.encode("utf-8")))


def forget_written(record: Path, reverted: Iterable[Path], *, created: bool) -> None:
    """Drop the reverted destinations from a write record, keeping everything else it
    says, so a file init wrote that stays is still known as loadout's. A record that
    does not parse is left alone: without one the guard accepts less, never more. One
    `created` with the run and emptied by this is removed."""
    document = _document(record)
    if (
        not isinstance(document, dict)
        or document.get("version") != VERSION
        or not isinstance(document.get("written"), dict)
    ):
        return
    gone = {entry_path(path) for path in reverted}
    remaining = {
        key: value
        for key, value in document["written"].items()
        if entry_path(Path(key)) not in gone
    }
    if not remaining and created:
        record.unlink()
        return
    _write_record(record, {**document, "written": remaining})


def accepts_text(entry: WrittenEntry | None, path: Path, actual: str) -> bool:
    return entry is not None and entry.norm_sha256 == sha256(normalise(path, actual).encode())


def accepts_bytes(entry: WrittenEntry | None, actual: bytes) -> bool:
    return accepts_digest(entry, sha256(actual))


def accepts_digest(entry: WrittenEntry | None, digest: str) -> bool:
    return entry is not None and entry.sha256 == digest


def text_entry(path: Path, content: str) -> WrittenEntry:
    return WrittenEntry(
        kind="text",
        sha256=sha256(content.encode()),
        norm_sha256=sha256(normalise(path, content).encode()),
    )


def frozen_entry(content: bytes) -> WrittenEntry:
    return WrittenEntry(kind="copied", sha256=sha256(content))


def copied_entry(source: Path, digest: Callable[[Path], str] = file_sha256) -> WrittenEntry:
    return WrittenEntry(kind="copied", sha256=digest(source))


def merged_entry(merged: Merged) -> WrittenEntry:
    """Every owned key, which retirement strips; only the guarded ones are hashed, since
    an evicted key the harness writes back is no edit, and moving it to a managed value is
    opting it in (review 3, batch 2.1)."""
    hashes = owned_hashes(merged.document, merged.guarded, merged.format) or {}
    return WrittenEntry(
        kind="merged",
        owned=tuple(sorted(merged.owned)),
        owned_sha256=tuple(sorted(hashes.items())),
    )


# The recorded hash of an owned key the document does not hold.
ABSENT = ""


def canonical(value: object) -> str:
    """One spelling per value, so `true` and `1`, or `1` and `1.0`, never compare equal
    the way they do in Python."""
    return json.dumps(value, sort_keys=True, ensure_ascii=False, default=str)


def owned_hashes(text: str, owned: Iterable[str], format_name: str) -> dict[str, str] | None:
    """Each owned key's hash in a shared document, `ABSENT` for one it does not hold, so
    only those are compared: the harness may change the rest freely. None when the
    document does not parse."""
    values = owned_values(text, owned, format_name)
    if values is None:
        return None
    return {
        name: sha256(canonical(values[name]).encode()) if name in values else ABSENT
        for name in sorted(owned)
    }


def _pairs(raw: object) -> tuple[tuple[str, str], ...]:
    if not isinstance(raw, dict):
        return ()
    return tuple(sorted((str(k), v) for k, v in raw.items() if isinstance(v, str)))


def owned_values(text: str, owned: Iterable[str], format_name: str) -> dict[str, Any] | None:
    """Each owned key the document holds, by name, or None when it does not parse or
    cannot hold them: a document that is not an object, or a scalar where an owned key
    needs a table (review 3, batch 2.10)."""
    try:
        document = (
            (json.loads(text) if format_name == "json" else tomllib.loads(text))
            if text.strip()
            else {}
        )
    except (ValueError, tomllib.TOMLDecodeError):
        return None
    if not isinstance(document, dict):
        return None
    found: dict[str, Any] = {}
    for name in sorted(owned):
        value: Any = document
        for part in (name,) if format_name == "json" else key_path(name):
            if not isinstance(value, dict):
                return None
            value = value.get(part, _MISSING)
            if value is _MISSING:
                break
        if value is not _MISSING:
            found[name] = value
    return found


_MISSING = object()
