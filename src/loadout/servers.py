"""MCP server definitions — where a server lives and how to reach it.

Distinct from the `mcp-permissions` slice, which renders *which tools may be
called* from permissions.toml's [mcp] section. The two share a word and nothing
else; conflating them has produced two recorded wrong conclusions, so this
module never touches Rules and that one never reads this file.
"""

from __future__ import annotations

import json
import re
import tomllib
from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

import tomlkit

from .errors import LoadoutError

__all__ = [
    "SERVERS_SOURCE",
    "Server",
    "auth_conflict",
    "is_http",
    "literal_header",
    "parse_servers",
    "render_claude_project_servers",
    "render_claude_servers",
    "render_codex_servers",
    "render_droid_servers",
    "render_opencode_servers",
    "render_pi_servers",
    "serialize_servers",
]

SERVERS_SOURCE = "mcp.toml"
Transport = Literal["http", "stdio"]
TRANSPORTS: tuple[Transport, ...] = ("http", "stdio")

HEADER_LINES = (
    "Generated by loadout from mcp.toml.",
    "Edits to this file are replaced on the next sync.",
)

# Rejected rather than ignored, because the failure is silent and shaped like a
# security bug: `auth_env_varr` parses fine, yields no auth var, and renders a
# server that connects unauthenticated with nothing saying so. `plugins.py`
# rejects stray keys for the same reason.
SERVER_KEYS = frozenset({"transport", "url", "auth_env_var", "headers", "command", "args", "env"})


@dataclass(frozen=True)
class Server:
    name: str
    transport: Transport
    url: str | None = None
    auth_env_var: str | None = None
    headers: Mapping[str, str] = field(default_factory=dict)
    command: str | None = None
    args: tuple[str, ...] = ()
    env: Mapping[str, str] = field(default_factory=dict)


def is_http(server: Server) -> bool:
    return server.transport == "http"


def literal_header(value: object) -> bool:
    """A header value every harness sends as written. Claude and Pi expand `${…}`,
    OpenCode `{env:…}`, Pi `$env:` and a leading `!`, and Codex none of them."""
    return (
        isinstance(value, str)
        and "$" not in value
        and "{" not in value
        and not value.startswith("!")
    )


def auth_conflict(auth_env_var: object, headers: Mapping[str, object]) -> str | None:
    """The header that would set Authorization a second time beside the auth variable.
    Header names are case-insensitive, so `authorization` counts too."""
    if not auth_env_var:
        return None
    return next((header for header in headers if header.casefold() == "authorization"), None)


def _headers(path: Path, name: str, spec: Mapping[str, Any]) -> dict[str, str]:
    headers = spec.get("headers", {})
    if not isinstance(headers, dict):
        raise LoadoutError(f"{path}: [{name}] headers must be a table")
    if headers and spec.get("transport") != "http":
        raise LoadoutError(f"{path}: [{name}] headers needs transport http")
    if (clash := auth_conflict(spec.get("auth_env_var"), headers)) is not None:
        raise LoadoutError(f"{path}: [{name}] sets auth_env_var and an {clash} header")
    for header, value in headers.items():
        if not literal_header(value):
            raise LoadoutError(
                f"{path}: [{name}] header {header} must be a literal string without $, {{ or a "
                "leading !, which harnesses interpolate differently"
            )
    return dict(headers)


def parse_servers(path: Path) -> dict[str, Server]:
    """Every server the file declares, in declaration order.

    Absent file means no servers, not an error: a source that offers no
    definitions contributes none, exactly as one offering no permissions.toml
    contributes no tier.
    """
    if not path.is_file():
        return {}
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as error:
        raise LoadoutError(f"{path}: invalid TOML: {error}") from error

    servers: dict[str, Server] = {}
    for name, spec in data.items():
        if not isinstance(spec, dict):
            raise LoadoutError(f"{path}: [{name}] must be a table")
        stray = sorted(set(spec) - SERVER_KEYS)
        if stray:
            raise LoadoutError(
                f"{path}: [{name}] unknown key(s) {', '.join(stray)} "
                f"(a server takes: {', '.join(sorted(SERVER_KEYS))})"
            )
        transport = spec.get("transport")
        if transport not in TRANSPORTS:
            raise LoadoutError(
                f"{path}: [{name}] unknown transport {transport!r} "
                f"(expected one of {', '.join(TRANSPORTS)})"
            )
        # Validated here rather than in five renderers: each would fail
        # differently, and four of them only when that harness is enabled.
        if transport == "http" and not spec.get("url"):
            raise LoadoutError(f"{path}: [{name}] transport is http, so it needs a url")
        if transport == "stdio" and not spec.get("command"):
            raise LoadoutError(f"{path}: [{name}] transport is stdio, so it needs a command")
        servers[name] = Server(
            name=name,
            transport=transport,
            url=spec.get("url"),
            auth_env_var=spec.get("auth_env_var"),
            headers=_headers(path, name, spec),
            command=spec.get("command"),
            args=tuple(spec.get("args", ())),
            env=dict(spec.get("env", {})),
        )
    return servers


def serialize_servers(servers: Mapping[str, Server]) -> bytes:
    document: dict[str, Any] = {}
    for name, server in servers.items():
        block: dict[str, Any] = {"transport": server.transport}
        if server.url is not None:
            block["url"] = server.url
        if server.auth_env_var is not None:
            block["auth_env_var"] = server.auth_env_var
        if server.headers:
            block["headers"] = dict(server.headers)
        if server.command is not None:
            block["command"] = server.command
        if server.args:
            block["args"] = list(server.args)
        if server.env:
            block["env"] = dict(server.env)
        document[name] = block
    return tomlkit.dumps(document).encode()


def _toml_string(value: str) -> str:
    return json.dumps(value)


def _toml_array(values: tuple[str, ...]) -> str:
    return "[" + ", ".join(_toml_string(v) for v in values) + "]"


def _toml_key(key: str) -> str:
    return key if re.fullmatch(r"[A-Za-z0-9_-]+", key) else _toml_string(key)


def _bearer_headers(server: Server, reference: str) -> dict[str, str]:
    """The auth variable as an Authorization header in the harness's own reference
    syntax, ahead of the literal headers."""
    auth = {"Authorization": f"Bearer {reference}"} if server.auth_env_var else {}
    return {**auth, **server.headers}


# --------------------------------------------------------------------------
# claude — .mcp.json (project) / the staged document `claude mcp add-json`
# consumes (global): the exact per-server shape that command takes, which is
# also how Claude stores a server once added. Header interpolation is ${VAR}.
# --------------------------------------------------------------------------


def render_claude_global_servers(servers: dict[str, Server]) -> dict[str, Any]:
    """Claude's global entry, as the `mcpServers` key of a file loadout does not own.

    The same per-server shape as project scope; only the wrapper and the ownership
    differ. `.mcp.json` is loadout's outright, `.claude.json` is the harness's with
    one key carved out.
    """
    return {"mcpServers": render_claude_servers(servers)}


def render_claude_servers(servers: dict[str, Server]) -> dict[str, Any]:
    config: dict[str, Any] = {}
    for name, server in servers.items():
        entry: dict[str, Any]
        if is_http(server):
            assert server.url is not None
            entry = {"type": "http", "url": server.url}
            headers = _bearer_headers(server, f"${{{server.auth_env_var}}}")
            if headers:
                entry["headers"] = headers
        else:
            assert server.command is not None
            entry = {
                "type": "stdio",
                "command": server.command,
                "args": list(server.args),
                "env": dict(server.env),
            }
        config[name] = entry
    return config


# --------------------------------------------------------------------------
# claude — .mcp.json (project scope). The flat per-server map `claude mcp
# add-json` and the global staged document take, wrapped in the key Claude's
# project file itself uses. Distinct from render_claude_servers the way
# render_claude_project is distinct from render_claude: same content, a
# different document shape for a different scope.
# --------------------------------------------------------------------------


def render_claude_project_servers(servers: dict[str, Server]) -> dict[str, Any]:
    return {"mcpServers": render_claude_servers(servers)}


def render_droid_servers(servers: dict[str, Server]) -> dict[str, Any]:
    return {"mcpServers": render_claude_servers(servers)}


# --------------------------------------------------------------------------
# codex — [mcp_servers.<name>] tables. Header comment guards the staged copy
# only; the caller merges this into Codex's config through tomllib, which
# drops the comment.
# --------------------------------------------------------------------------


def render_codex_servers(servers: dict[str, Server]) -> str:
    lines = [f"# {line}" for line in HEADER_LINES]
    for name, server in servers.items():
        lines.append("")
        lines.append(f"[mcp_servers.{name}]")
        if is_http(server):
            assert server.url is not None
            lines.append(f"url = {_toml_string(server.url)}")
            if server.auth_env_var:
                lines.append(f"bearer_token_env_var = {_toml_string(server.auth_env_var)}")
            if server.headers:
                lines.append("")
                lines.append(f"[mcp_servers.{name}.http_headers]")
                for key, value in server.headers.items():
                    lines.append(f"{_toml_key(key)} = {_toml_string(value)}")
        else:
            assert server.command is not None
            lines.append(f"command = {_toml_string(server.command)}")
            if server.args:
                lines.append(f"args = {_toml_array(server.args)}")
            variables = dict(server.env)
            if variables:
                lines.append("")
                lines.append(f"[mcp_servers.{name}.env]")
                for key in sorted(variables):
                    lines.append(f"{key} = {_toml_string(variables[key])}")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------
# opencode — the `mcp` key's value, one key of a document `permission` also
# owns. A local server takes one `command` array combining command and args,
# not separate fields, and interpolation is {env:VAR} rather than ${VAR}.
# --------------------------------------------------------------------------


def render_opencode_servers(servers: dict[str, Server]) -> dict[str, Any]:
    mcp: dict[str, Any] = {}
    for name, server in servers.items():
        entry: dict[str, Any]
        if is_http(server):
            assert server.url is not None
            entry = {"type": "remote", "url": server.url}
            headers = _bearer_headers(server, f"{{env:{server.auth_env_var}}}")
            if headers:
                entry["headers"] = headers
        else:
            assert server.command is not None
            entry = {"type": "local", "command": [server.command, *server.args]}
            variables = dict(server.env)
            if variables:
                entry["environment"] = variables
        mcp[name] = entry
    return mcp


# --------------------------------------------------------------------------
# pi — `mcpServers`, the shape pi-mcp-adapter's ServerEntry takes. HTTP auth
# uses `bearerTokenEnv` (the variable NAME; the adapter reads it at call
# time), so no token is ever written here.
# --------------------------------------------------------------------------


def render_pi_servers(servers: dict[str, Server]) -> dict[str, Any]:
    entries: dict[str, Any] = {}
    for name, server in servers.items():
        entry: dict[str, Any]
        if is_http(server):
            assert server.url is not None
            entry = {"url": server.url}
            if server.auth_env_var:
                entry["bearerTokenEnv"] = server.auth_env_var
            if server.headers:
                entry["headers"] = dict(server.headers)
        else:
            assert server.command is not None
            entry = {"command": server.command, "args": list(server.args)}
            variables = dict(server.env)
            if variables:
                entry["env"] = variables
        entries[name] = entry
    return {"mcpServers": entries}
