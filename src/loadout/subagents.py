"""The agents slice: one source agent rendered to each harness's subagent format (S-26).

A source agent is `agents/<name>.md`: frontmatter naming the agent, describing it and
choosing a model and effort per harness, and a body that becomes its instructions.
Claude, Droid, OpenCode and Pi read Markdown with frontmatter; Codex reads TOML, with
the body as `developer_instructions`.

Identity is the file name. Claude, Codex, Droid and Pi identify an agent by its `name`
field and OpenCode by its file name, so the two must agree for a rename to retire the
old file everywhere; `name` may be omitted and is otherwise checked against it.
"""

from __future__ import annotations

import json
import re
from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import Path

import tomlkit

from .errors import LoadoutError
from .harnesses import KNOWN_HARNESSES
from .output import item_name
from .skills import _TOP_LEVEL_KEY, apply_body, split_frontmatter

AGENTS_SUBDIR = "agents"

BANNER = "Generated by loadout from agents/{name}.md. Edits here are replaced on the next sync."

# The shared vocabulary, lowest first. A harness missing a level gets the nearest
# lower one it has; Codex's `ultra` and `persistent` sit on no common scale and are
# reachable only through a per-harness map.
EFFORT_SCALE = ("off", "minimal", "low", "medium", "high", "xhigh", "max")
EFFORT_LEVELS: dict[str, tuple[str, ...]] = {
    "claude": ("low", "medium", "high", "xhigh", "max"),
    "codex": ("off", "minimal", "low", "medium", "high", "xhigh", "max"),
    "droid": ("low", "medium", "high"),
    "pi": ("off", "minimal", "low", "medium", "high", "xhigh", "max"),
}
EFFORT_SPELLING: dict[str, dict[str, str]] = {"codex": {"off": "none"}}
EFFORT_KEY = {
    "claude": "effort",
    "codex": "model_reasoning_effort",
    "droid": "reasoningEffort",
    "pi": "thinking",
}
EXTENSION = {"codex": ".toml"}
SOURCE_KEYS = frozenset({"name", "description", "model", "effort"})


@dataclass(frozen=True)
class Agent:
    name: str
    description: str
    body: str
    models: Mapping[str, str] = field(default_factory=dict)
    effort: str | None = None
    efforts: Mapping[str, str] = field(default_factory=dict)
    extra: Mapping[str, tuple[str, ...]] = field(default_factory=dict)


def agent_file_name(name: str, harness: str) -> str:
    return f"{name}{EXTENSION.get(harness, '.md')}"


def discover_agents(directory: Path) -> tuple[Path, ...]:
    if not directory.is_dir():
        return ()
    found = sorted(p for p in directory.iterdir() if p.is_file() and p.suffix == ".md")
    return tuple(p for p in found if item_name(p.stem, p))


_BLOCK = re.compile(r"([|>])([+-]?)")


def yaml_text(value: str, children: list[str], label: str) -> str:
    """The text one frontmatter scalar holds: plain, single- or double-quoted, or a
    `|` or `>` block over the indented lines beneath it."""
    block = _BLOCK.fullmatch(value)
    if block is not None:
        return _block_text(block.group(1), block.group(2), children)
    if children:
        raise LoadoutError(f"{label}: a value over several lines must be a `|` or `>` block")
    if value[:1] == '"':
        try:
            decoded = json.loads(value)
        except ValueError:
            raise LoadoutError(f"{label}: unreadable double-quoted value {value!r}") from None
        if not isinstance(decoded, str):
            raise LoadoutError(f"{label}: unreadable double-quoted value {value!r}")
        return decoded
    if value[:1] == "'" and value.endswith("'") and len(value) > 1:
        return value[1:-1].replace("''", "'")
    return value


def _block_text(style: str, chomp: str, children: list[str]) -> str:
    indent = min((len(line) - len(line.lstrip()) for line in children if line.strip()), default=0)
    lines = [line[indent:] for line in children]
    if style == "|":
        text = "\n".join(lines)
    else:
        paragraphs: list[list[str]] = [[]]
        for line in lines:
            if line.strip():
                paragraphs[-1].append(line)
            elif paragraphs[-1]:
                paragraphs.append([])
        text = "\n".join(" ".join(paragraph) for paragraph in paragraphs if paragraph)
    if chomp == "-":
        return text.rstrip("\n")
    return text.rstrip("\n") + "\n" if chomp == "" else text + "\n"


def yaml_string(text: str) -> str:
    """A double-quoted scalar: valid YAML whatever the text holds."""
    return json.dumps(text, ensure_ascii=False)


def _unquote(value: str) -> str:
    return yaml_text(value, [], "frontmatter")


def _blocks(lines: list[str], label: str) -> dict[str, tuple[str, list[str]]]:
    """Top-level `key: value` lines, each with the indented lines beneath it."""
    found: dict[str, tuple[str, list[str]]] = {}
    current: str | None = None
    for line in lines:
        if not line.strip():
            continue
        if line[:1].isspace():
            if current is None:
                raise LoadoutError(f"{label}: indented line before any key: {line!r}")
            found[current][1].append(line)
            continue
        match = _TOP_LEVEL_KEY.match(line)
        if match is None:
            raise LoadoutError(f"{label}: unreadable frontmatter line {line!r}")
        current = match.group(1)
        if current in found:
            raise LoadoutError(f"{label}: {current!r} is given twice")
        found[current] = (match.group(2).strip(), [])
    return found


def _harness_map(children: list[str], label: str, key: str) -> dict[str, str]:
    mapped: dict[str, str] = {}
    for line in children:
        match = _TOP_LEVEL_KEY.match(line.strip())
        if match is None or match.group(1) not in KNOWN_HARNESSES:
            raise LoadoutError(
                f"{label}: {key} maps harness names to values "
                f"({', '.join(sorted(KNOWN_HARNESSES))}), got {line.strip()!r}"
            )
        mapped[match.group(1)] = _unquote(match.group(2).strip())
    return mapped


def parse_agent(path: Path) -> Agent:
    label = f"agents/{path.name}"
    frontmatter, body = split_frontmatter(path.read_text(encoding="utf-8"))
    if frontmatter is None:
        raise LoadoutError(f"{label}: an agent needs frontmatter with a description")
    blocks = _blocks(frontmatter, label)
    unknown = sorted(set(blocks) - SOURCE_KEYS - KNOWN_HARNESSES)
    if unknown:
        raise LoadoutError(
            f"{label}: unknown key(s) {', '.join(unknown)}; an agent takes name, description, "
            f"model, effort, and a block per harness for anything harness-specific"
        )
    name = _unquote(blocks.get("name", (path.stem, []))[0])
    if name != path.stem:
        raise LoadoutError(
            f"{label}: name {name!r} differs from the file name; OpenCode names an agent by "
            f"its file and the others by `name`, so the two must agree"
        )
    description = yaml_text(*blocks.get("description", ("", [])), label)
    if not description:
        raise LoadoutError(f"{label}: description is required; every harness needs one")
    models = _models(blocks.get("model"), label)
    effort, efforts = _efforts(blocks.get("effort"), label)
    extra = {
        harness: tuple(_dedent(children))
        for harness, (value, children) in blocks.items()
        if harness in KNOWN_HARNESSES
    }
    for harness, lines in extra.items():
        reserved = sorted(
            key
            for line in lines
            if (match := _TOP_LEVEL_KEY.match(line)) and (key := match.group(1)) in SOURCE_KEYS
        )
        if reserved:
            raise LoadoutError(
                f"{label}: {harness}'s block sets {', '.join(reserved)}; give those at the top "
                "level, where model and effort take a per-harness map"
            )
    return Agent(name, description, body, models, effort, efforts, extra)


def _dedent(lines: list[str]) -> list[str]:
    indent = min((len(line) - len(line.lstrip()) for line in lines if line.strip()), default=0)
    return [line[indent:] for line in lines]


def _models(block: tuple[str, list[str]] | None, label: str) -> dict[str, str]:
    if block is None:
        return {}
    value, children = block
    if value and children:
        raise LoadoutError(f"{label}: model is either `inherit` or a per-harness map, not both")
    if value:
        if _unquote(value) == "inherit":
            return {}
        raise LoadoutError(
            f"{label}: model {_unquote(value)!r} would name one model for every harness, and "
            f"no model name means the same thing in all five; give a per-harness map, one "
            f"indented `<harness>: <model>` line each, or `inherit`"
        )
    models = _harness_map(children, label, "model")
    opencode = models.get("opencode")
    if opencode is not None and "/" not in opencode:
        raise LoadoutError(
            f"{label}: OpenCode's model {opencode!r} needs the provider/model-id form"
        )
    return models


def _efforts(block: tuple[str, list[str]] | None, label: str) -> tuple[str | None, dict[str, str]]:
    if block is None:
        return None, {}
    value, children = block
    if value and children:
        raise LoadoutError(f"{label}: effort is either one word or a per-harness map, not both")
    if children:
        return None, _harness_map(children, label, "effort")
    word = _unquote(value)
    if word not in EFFORT_SCALE:
        raise LoadoutError(
            f"{label}: effort {word!r} is not one of {', '.join(EFFORT_SCALE)}; a value only "
            f"one harness knows belongs in a per-harness map"
        )
    return word, {}


def effort_for(agent: Agent, harness: str) -> tuple[str | None, str | None]:
    """The effort value this harness gets, and a note when it is not the one written."""
    if harness == "opencode":
        return None, _opencode_effort_note(agent)
    if harness in agent.efforts:
        return agent.efforts[harness], None
    if agent.effort is None or harness not in EFFORT_LEVELS:
        return None, None
    levels = EFFORT_LEVELS[harness]
    lower = [
        level for level in EFFORT_SCALE[: EFFORT_SCALE.index(agent.effort) + 1] if level in levels
    ]
    if not lower:
        return None, (
            f"agent {agent.name!r}: {harness} has no effort level at or below "
            f"{agent.effort!r}, so none is written and it inherits"
        )
    chosen = lower[-1]
    spelled = EFFORT_SPELLING.get(harness, {}).get(chosen, chosen)
    if chosen == agent.effort:
        return spelled, None
    return spelled, (
        f"agent {agent.name!r}: {harness} has no effort {agent.effort!r}, so {spelled!r}, the "
        f"nearest lower level, is written"
    )


def _opencode_effort_note(agent: Agent) -> str | None:
    stated = agent.efforts.get("opencode") or agent.effort
    if stated is None:
        return None
    return (
        f"agent {agent.name!r}: OpenCode agents have no effort field, so effort "
        f"{stated!r} is not written for OpenCode"
    )


def agent_notes(agent: Agent, harnesses: tuple[str, ...]) -> tuple[tuple[str, str], ...]:
    return tuple(
        (harness, note)
        for harness in harnesses
        if (note := effort_for(agent, harness)[1]) is not None
    )


def render_agent(agent: Agent, harness: str) -> str:
    body = apply_body(agent.body, harness, f"agents/{agent.name}.md")
    if harness == "codex":
        return _render_codex(agent, body)
    effort, _ = effort_for(agent, harness)
    extra = agent.extra.get(harness, ())
    lines = [] if harness == "opencode" else [f"name: {agent.name}"]
    lines.append(f"description: {yaml_string(agent.description)}")
    if harness == "opencode" and not any(line.startswith("mode:") for line in extra):
        # Omitted, OpenCode's mode is `all`, which also lists the agent as a primary one.
        lines.append("mode: subagent")
    if (model := agent.models.get(harness)) is not None:
        lines.append(f"model: {model}")
    if effort is not None:
        lines.append(f"{EFFORT_KEY[harness]}: {effort}")
    lines.extend(extra)
    banner = f"<!-- {BANNER.format(name=agent.name)} -->"
    return "---\n" + "\n".join(lines) + "\n---\n\n" + banner + "\n" + body


def _scalar(value: str) -> object:
    """A plain `true`, `false` or integer keeps its TOML type; anything else is text,
    so a quoted "true" stays a string."""
    if value in {"true", "false"}:
        return value == "true"
    if value.lstrip("-").isdigit():
        return int(value)
    return _unquote(value)


def _render_codex(agent: Agent, body: str) -> str:
    document = tomlkit.document()
    document.add(tomlkit.comment(BANNER.format(name=agent.name)))
    document.add("name", agent.name)
    document.add("description", agent.description)
    if (model := agent.models.get("codex")) is not None:
        document.add("model", model)
    effort, _ = effort_for(agent, "codex")
    if effort is not None:
        document.add("model_reasoning_effort", effort)
    for line in agent.extra.get("codex", ()):
        match = _TOP_LEVEL_KEY.match(line)
        if match is None:
            raise LoadoutError(
                f"agents/{agent.name}.md: codex's block takes `key: value` lines, got {line!r}"
            )
        document.add(match.group(1), _scalar(match.group(2).strip()))
    document.add("developer_instructions", tomlkit.string(body.lstrip("\n"), multiline=True))
    return tomlkit.dumps(document)


@dataclass(frozen=True)
class NativeAgent:
    """One harness's agent file read back into the source's terms."""

    name: str
    description: str
    body: str
    model: str | None = None
    effort: str | None = None
    extra: tuple[str, ...] = ()


def _strip_banner(body: str, name: str) -> str:
    return body.removeprefix(f"\n<!-- {BANNER.format(name=name)} -->\n")


def extract_agent(harness: str, text: str, stem: str) -> NativeAgent:
    """The renderer run backwards; `stem` is the file name without its extension."""
    if harness == "codex":
        return _extract_codex(text, stem)
    label = f"{harness} agent {stem}"
    frontmatter, body = split_frontmatter(text)
    if frontmatter is None:
        raise LoadoutError(f"{label}: no frontmatter")
    blocks = _blocks(frontmatter, label)
    name = _unquote(blocks.get("name", (stem, []))[0])
    effort_key = EFFORT_KEY.get(harness)
    known = {"name", "description", "model", *((effort_key,) if effort_key else ())}
    extra: list[str] = []
    for key, (value, children) in blocks.items():
        if key in known or (harness == "opencode" and key == "mode" and value == "subagent"):
            continue
        extra.append(f"{key}: {value}" if value else f"{key}:")
        extra.extend(children)
    model = blocks.get("model", ("", []))[0]
    effort = blocks.get(effort_key, ("", []))[0] if effort_key else ""
    return NativeAgent(
        name=name,
        description=yaml_text(*blocks.get("description", ("", [])), label),
        body=_strip_banner(body, name),
        model=_unquote(model) if model and _unquote(model) != "inherit" else None,
        effort=_unquote(effort) or None,
        extra=tuple(extra),
    )


def _extract_codex(text: str, stem: str) -> NativeAgent:
    document = tomlkit.parse(text).unwrap()
    name = document.pop("name", stem)
    extra: list[str] = []
    for key, value in document.items():
        if key in {"description", "model", "model_reasoning_effort", "developer_instructions"}:
            continue
        if isinstance(value, bool):
            extra.append(f"{key}: {'true' if value else 'false'}")
        elif isinstance(value, int):
            extra.append(f"{key}: {value}")
        elif isinstance(value, str):
            extra.append(f"{key}: {yaml_string(value)}")
        else:
            raise LoadoutError(
                f"codex agent {stem}: {key!r} holds a {type(value).__name__}, which a source "
                f"agent's frontmatter cannot carry"
            )
    effort = document.get("model_reasoning_effort")
    reverse = {v: k for k, v in EFFORT_SPELLING["codex"].items()}
    return NativeAgent(
        name=str(name),
        description=str(document.get("description", "")),
        body="\n" + str(document.get("developer_instructions", "")),
        model=document.get("model"),
        effort=reverse.get(effort, effort) if effort is not None else None,
        extra=tuple(extra),
    )
