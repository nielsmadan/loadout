"""Shell completion scripts for bash, zsh and fish, generated from the parser by shtab.

The script is static: it is regenerated on `install`, never at TAB time, so
completion costs no Python start-up. `status` compares the installed file with a
fresh render, which is what makes a stale script visible after an upgrade.
"""

from __future__ import annotations

import argparse
import os
import subprocess
from collections.abc import Mapping
from enum import Enum
from pathlib import Path

import shtab

from .errors import LoadoutError, UsageError

SHELLS = ("bash", "zsh", "fish")
MARKER = "# Generated by `loadout integrate completions install`. Edits are replaced on reinstall."

ACTIVATION = {
    "bash": "loaded on demand by bash-completion 2; without it, add `source {path}` to ~/.bashrc",
    "zsh": "add `fpath=({dir} $fpath)` before `compinit` in ~/.zshrc if that directory is not "
    "already on fpath",
    "fish": "loaded automatically by fish",
}


class CompletionState(Enum):
    ABSENT = "not installed"
    CURRENT = "installed and current"
    STALE = "installed but out of date; run `loadout integrate completions install`"
    FOREIGN = "present but not written by loadout; left alone"


def render(shell: str, parser: argparse.ArgumentParser) -> str:
    """The script, with the marker after zsh's `#compdef` line, which must stay first."""
    lines = shtab.complete(parser, shell=shell).splitlines()
    at = 1 if lines and lines[0].startswith("#compdef") else 0
    return "\n".join([*lines[:at], MARKER, *lines[at:]]).rstrip("\n") + "\n"


def completion_path(shell: str, environ: Mapping[str, str], home: Path) -> Path:
    data = Path(environ.get("XDG_DATA_HOME") or home / ".local" / "share")
    if shell == "bash":
        user_dir = environ.get("BASH_COMPLETION_USER_DIR")
        base = Path(user_dir) if user_dir else data / "bash-completion"
        return base / "completions" / "loadout"
    if shell == "zsh":
        return data / "zsh" / "site-functions" / "_loadout"
    config = Path(environ.get("XDG_CONFIG_HOME") or home / ".config")
    return config / "fish" / "completions" / "loadout.fish"


def detect_shell(parent: str | None, environ: Mapping[str, str]) -> str | None:
    """The shell that ran loadout, else the login shell, else None.

    The parent process is the invoking shell when loadout is run directly; under a
    wrapper such as `uv run` it is not, and `$SHELL` is the better guess.
    """
    for candidate in (parent, environ.get("SHELL")):
        name = Path(candidate or "").name.removeprefix("-")
        if name in SHELLS:
            return name
    return None


def classify(existing: str | None, expected: str) -> CompletionState:
    if existing is None:
        return CompletionState.ABSENT
    if MARKER not in existing:
        return CompletionState.FOREIGN
    return CompletionState.CURRENT if existing == expected else CompletionState.STALE


def _parent_command() -> str | None:
    try:
        result = subprocess.run(
            ["ps", "-o", "comm=", "-p", str(os.getppid())],
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError:
        return None
    return result.stdout.strip() or None


def resolve_shell(explicit: str | None) -> str:
    if explicit:
        return explicit
    shell = detect_shell(_parent_command(), os.environ)
    if shell is None:
        raise UsageError(f"cannot tell which shell is running; pass --shell {{{','.join(SHELLS)}}}")
    return shell


def _read(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None


def _hint(shell: str, path: Path) -> str:
    return ACTIVATION[shell].format(path=path, dir=path.parent)


def install_completions(shell: str, parser: argparse.ArgumentParser) -> int:
    path = completion_path(shell, os.environ, Path.home())
    expected = render(shell, parser)
    state = classify(_read(path), expected)
    if state is CompletionState.FOREIGN:
        raise LoadoutError(f"{path} exists and was not written by loadout; remove it first")
    if state is CompletionState.CURRENT:
        print(f"{shell} completions already current at {path}")
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(expected, encoding="utf-8")
    print(f"wrote {shell} completions to {path}")
    print(f"  {_hint(shell, path)}")
    return 0


def status_completions(shell: str, parser: argparse.ArgumentParser) -> int:
    path = completion_path(shell, os.environ, Path.home())
    state = classify(_read(path), render(shell, parser))
    print(f"{shell}: {state.value} ({path})")
    return 0


def uninstall_completions(shell: str, parser: argparse.ArgumentParser) -> int:
    path = completion_path(shell, os.environ, Path.home())
    state = classify(_read(path), render(shell, parser))
    if state is CompletionState.ABSENT:
        print(f"no loadout {shell} completions at {path}; no changes made")
        return 0
    if state is CompletionState.FOREIGN:
        print(f"{path} was not written by loadout; left alone")
        return 0
    path.unlink()
    print(f"removed {path}")
    return 0
