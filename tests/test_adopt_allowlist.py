def _snapshot(root: Path) -> dict[str, object]:
    result: dict[str, object] = {}
    for directory, directories, files in os.walk(root):
        for name in (*directories, *files):
            path = Path(directory) / name
            key = path.relative_to(root).as_posix()
            if path.is_symlink():
                result[key] = ("link", os.readlink(path))
            elif path.is_dir():
                result[key] = "dir"
            else:
                result[key] = (path.read_bytes(), path.stat().st_mode)
    return result


def _claude(home: Path) -> Path:
    claude = home / ".claude"
    for relative, content in {**MANAGED, **UNMANAGED}.items():
        (claude / relative).parent.mkdir(parents=True, exist_ok=True)
        (claude / relative).write_text(content)
    (claude / "hooks/guard.sh").chmod(0o755)
    (claude / "debug").mkdir()
    (claude / "debug/latest").symlink_to(claude / "debug/missing.txt")
    return claude


def _unmanaged(snapshot: dict[str, object]) -> dict[str, object]:
    return {
        key: value
        for key, value in snapshot.items()
        if key not in MANAGED
        and key not in {"skills", "skills/review", "hooks", "agents", "mcp-permissions.json"}
    }


def test_a_realistic_claude_directory_adopts_only_what_loadout_manages(
    tmp_path: Path, fake_home: Path, capsys
) -> None:
    claude = _claude(fake_home)
    before = _snapshot(claude)
    source = tmp_path / "agent-config"
    source.mkdir()
    init = ["init", "global", str(source), "--harness", "claude"]

    assert loadout.main([*init, "--dry-run", "--json"]) == 0
    preview = json.loads(capsys.readouterr().out)
    assert preview["issues"] == []
    assert {
        Path(c["path"]).relative_to(claude).as_posix()
        for c in preview["candidates"]
        if Path(c["path"]).is_relative_to(claude)
    } == set(MANAGED)

    assert loadout.main([*init, "--yes"]) == 0

    assert _unmanaged(_snapshot(claude)) == _unmanaged(before)
    assert "Generated by loadout" in (claude / "CLAUDE.md").read_text()
    assert json.loads((claude / "settings.json").read_text())["permissions"]["allow"] == [
        "Bash(git status)"
    ]
    written = {
        path.relative_to(source / "loadout").as_posix()
        for path in (source / "loadout").rglob("*")
        if path.is_file()
    }
    assert {
        "instructions/claude.md",
        "settings/claude.json",
        "skills/review/SKILL.md",
        "agents/auditor.md",
        "module-config/claude/hooks/guard.sh",
    } <= written
    capsys.readouterr()
    assert loadout.main(["sync", "--global"]) == 0
    assert "Up to date." in capsys.readouterr().out
    assert _unmanaged(_snapshot(claude)) == _unmanaged(before)


def test_a_managed_file_inside_an_unmanaged_directory_is_still_read(
    tmp_path: Path, fake_home: Path
) -> None:
    pi = fake_home / ".pi/agent"
    config = pi / "extensions/pi-permission-system/config.json"
    config.parent.mkdir(parents=True)
    rules = Rules(allow=("git status",), deny=("rm -rf",))
    config.write_text(json.dumps(render_pi(rules, {}), indent=2) + "\n")
    other = pi / "extensions/subagent/index.ts"
    other.parent.mkdir(parents=True)
    other.write_text("export default {}\n")
    source = tmp_path / "agent-config"
    source.mkdir()

    plan = plan_migration(discover(source, scope="global", agents=("pi",)))

    read = {c.path for c in plan.inventory.candidates}
    assert config in read
    assert other not in read
    permissions = next(w for w in plan.source_writes if w.path.name == "permissions.toml")
    assert "git status" in permissions.content.decode()
    assert "rm -rf" in permissions.content.decode()
