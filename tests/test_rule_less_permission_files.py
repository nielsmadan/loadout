"""A whole permission file with no rule in it is not written (P-44, following P-35).

Keys inside shared files are still claimed and written empty, and Pi's global
`config.json` is still written: its empty render carries a policy (`bash` asks).
Pi's project file carries none when empty, so it follows the rule.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

import loadout
from loadout.emit import render_global, render_project
from loadout.permissions.renderers import render_codex
from loadout.permissions.rules import Rules

HARNESSES = ("claude", "codex", "droid", "opencode", "pi")


def _global(root: Path, permissions: str) -> Path:
    root.mkdir()
    blocks = "".join(f"\n[{agent}]\n" for agent in HARNESSES)
    (root / "loadout.toml").write_text(f'[[source]]\nname = "t"\npath = "."\n{blocks}')
    (root / "permissions.toml").write_text(permissions)
    return root


def _project(root: Path, permissions: str) -> Path:
    (root / "loadout").mkdir(parents=True)
    (root / "loadout" / "config.toml").write_text(f"harnesses = {json.dumps(list(HARNESSES))}\n")
    (root / "loadout" / "permissions.toml").write_text(permissions)
    return root


def _relative(outputs: dict[Path, object], base: Path) -> set[str]:
    return {path.relative_to(base).as_posix() for path in outputs}


def test_global_scope_writes_no_rule_less_whole_permission_file(
    tmp_path: Path, fake_home: Path
) -> None:
    written = _relative(render_global(_global(tmp_path / "g", "")), fake_home)

    assert {
        ".claude/settings.json",
        ".factory/settings.json",
        ".config/opencode/opencode.json",
        ".pi/agent/extensions/pi-permission-system/config.json",
    } <= written
    assert ".codex/rules/permissions.rules" not in written
    assert ".claude/mcp-permissions.json" not in written


def test_project_scope_writes_no_rule_less_whole_permission_file(tmp_path: Path) -> None:
    root = _project(tmp_path / "p", "")

    written = _relative(render_project(root), root)

    assert {
        ".claude/settings.json",
        ".factory/settings.json",
        "opencode.json",
    } <= written
    assert ".codex/rules/permissions.rules" not in written
    assert ".claude/mcp-permissions.json" not in written
    assert ".pi/extensions/pi-permission-system/config.json" not in written


def test_a_rule_brings_the_whole_files_back(tmp_path: Path, fake_home: Path) -> None:
    rules = '[shell]\ndeny = ["rm"]\n\n[mcp]\ndeny = ["jina/*"]\n'

    written = _relative(render_global(_global(tmp_path / "g", rules)), fake_home)

    assert {".codex/rules/permissions.rules", ".claude/mcp-permissions.json"} <= written


def test_codex_with_only_glob_entries_has_no_rule_to_write(tmp_path: Path, fake_home: Path) -> None:
    written = _relative(
        render_global(_global(tmp_path / "g", '[shell]\nallow = ["gamma-*"]\n')), fake_home
    )

    assert ".codex/rules/permissions.rules" not in written


def test_the_codex_header_asserts_no_policy() -> None:
    document = render_codex(Rules(deny=("rm",)))

    assert document.splitlines()[:3] == [
        "# Generated by loadout from permissions.toml.",
        "# Edits to this file are replaced on the next sync.",
        "",
    ]
    assert 'prefix_rule(pattern = ["rm"], decision = "forbidden")' in document


@pytest.mark.integration
def test_sync_retires_a_whole_file_once_its_last_rule_is_gone(tmp_path: Path) -> None:
    root = _project(tmp_path / "p", '[shell]\ndeny = ["rm"]\n\n[mcp]\ndeny = ["jina/*"]\n')
    assert loadout.main(["sync", "--root", str(root)]) == 0
    rules = root / ".codex" / "rules" / "permissions.rules"
    mcp = root / ".claude" / "mcp-permissions.json"
    assert rules.is_file()
    assert mcp.is_file()

    (root / "loadout" / "permissions.toml").write_text("")
    assert loadout.main(["sync", "--root", str(root)]) == 0

    assert not rules.exists()
    assert not mcp.exists()
    assert json.loads((root / ".claude" / "settings.json").read_text())["permissions"] == {
        "allow": [],
        "ask": [],
        "deny": [],
    }


@pytest.mark.migration_integration
def test_a_codex_only_global_init_creates_no_empty_files(
    tmp_path: Path, fake_home: Path, capsys
) -> None:
    (fake_home / ".codex").mkdir()
    source = tmp_path / "source"
    source.mkdir()

    assert loadout.main(["init", "global", str(source), "--harness", "codex", "--yes"]) == 0

    assert sorted(p.name for p in (fake_home / ".codex").rglob("*")) == []
    # The preview must not announce a file that is never created.
    assert str(fake_home / ".codex" / "config.toml") not in capsys.readouterr().out
    assert loadout.main(["sync", "--global"]) == 0
    assert "Up to date." in capsys.readouterr().out


@pytest.mark.integration
def test_a_profile_selecting_no_rules_retires_the_codex_file_until_switched_back(
    tmp_path: Path, fake_home: Path
) -> None:
    """`permissions = []` empties what one target renders; the check must see that, not
    the source's rules, or the file is written holding no rule."""
    source = tmp_path / "source"
    source.mkdir()
    (source / "loadout.toml").write_text(
        '[[source]]\nname = "me"\npath = "."\n\n[codex]\npermissions = true\n'
    )
    (source / "autonomous.toml").write_text('extends = "default"\n\n[codex]\npermissions = []\n')
    (source / "permissions.toml").write_text('[shell]\ndeny = ["rm"]\n')
    machine = fake_home / ".config" / "loadout"
    machine.mkdir(parents=True)
    (machine / "config.toml").write_text(f'source = "{source}"\n')
    rules = fake_home / ".codex" / "rules" / "permissions.rules"

    assert loadout.main(["sync", "--global"]) == 0
    assert 'prefix_rule(pattern = ["rm"], decision = "forbidden")' in rules.read_text()
    assert loadout.main(["sync", "--global", "--profile", "autonomous"]) == 0
    assert not rules.exists()
    assert loadout.main(["sync", "--global"]) == 0
    assert 'prefix_rule(pattern = ["rm"], decision = "forbidden")' in rules.read_text()
