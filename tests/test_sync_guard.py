def test_a_reworded_banner_is_not_a_hand_edit(root: Path, capsys) -> None:
    """The banner is loadout's own text, so changing it is not evidence a user
    touched the file. Without this, rewording it makes every generated file on
    disk differ from every acceptable variant at once and the guard reports the
    whole tree as hand-edited — which it did, on 205 files."""
    register(root)
    _adopt(root)
    output = root / "out" / "shared.md"
    body = output.read_text(encoding="utf-8").split("\n", 1)[1]
    output.write_text(
        "<!-- GENERATED by loadout — do not edit. Edit the fragments and re-run. -->\n" + body,
        encoding="utf-8",
    )
    capsys.readouterr()

    assert loadout.main(["sync", "--root", str(root)]) == 0
    assert "modified outside loadout" not in capsys.readouterr().err


def test_the_normaliser_strips_a_slash_slash_banner_too(root: Path) -> None:
    """The generated hook adapters are JavaScript and TypeScript, so their banner
    is `//`. A stripper knowing only `#` and `<!--` would leave it in the compared
    text and reintroduce the whole-tree false positive for exactly those files —
    the failure this normaliser exists to prevent, reappearing where it is least
    expected because every other generated file comments differently.
    """
    banner = "// Generated by loadout from hooks/*.json.\n"
    consequence = "// Edits to this file are replaced on the next sync.\n"
    body = "const HOOKS = {}\n"
    plugin = root / "loadout-hooks.js"

    assert _normalise(plugin, banner + consequence + body) == _normalise(
        plugin, "// Generated by loadout — do not edit.\n" + body
    )


