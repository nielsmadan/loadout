"""One source agent rendered to each harness's subagent format, and read back (S-26)."""

from __future__ import annotations

import tomllib
from pathlib import Path

import pytest

from loadout.errors import LoadoutError
from loadout.harnesses import KNOWN_HARNESSES
from loadout.skills import apply_body
from loadout.subagents import (
    Agent,
    agent_notes,
    effort_for,
    extract_agent,
    parse_agent,
    render_agent,
)

SOURCE = """\
---
name: reviewer
description: Reviews a diff for defects.
model:
  claude: sonnet
  codex: gpt-5.5
  opencode: anthropic/claude-sonnet-5-5
effort: high
claude:
  tools: Read, Grep
---

Review the diff.

::: codex
Use `git diff` yourself.
:::
"""


def _agent(tmp_path: Path, text: str = SOURCE, name: str = "reviewer") -> Agent:
    path = tmp_path / f"{name}.md"
    path.write_text(text)
    return parse_agent(path)


def test_claude_gets_its_model_effort_and_own_block(tmp_path: Path) -> None:
    rendered = render_agent(_agent(tmp_path), "claude")

    assert rendered == (
        "---\n"
        "name: reviewer\n"
        "description: Reviews a diff for defects.\n"
        "model: sonnet\n"
        "effort: high\n"
        "tools: Read, Grep\n"
        "---\n\n"
        "<!-- Generated by loadout from agents/reviewer.md. Edits here are replaced on the "
        "next sync. -->\n"
        "\nReview the diff.\n\n"
    )


def test_codex_gets_toml_with_the_body_as_developer_instructions(tmp_path: Path) -> None:
    document = tomllib.loads(render_agent(_agent(tmp_path), "codex"))

    assert document == {
        "name": "reviewer",
        "description": "Reviews a diff for defects.",
        "model": "gpt-5.5",
        "model_reasoning_effort": "high",
        "developer_instructions": "Review the diff.\n\nUse `git diff` yourself.\n",
    }


def test_opencode_is_named_by_its_file_and_marked_a_subagent(tmp_path: Path) -> None:
    rendered = render_agent(_agent(tmp_path), "opencode")

    assert rendered.startswith(
        "---\n"
        "description: Reviews a diff for defects.\n"
        "mode: subagent\n"
        "model: anthropic/claude-sonnet-5-5\n"
        "---\n"
    )


def test_a_harness_the_model_map_omits_gets_no_model_line(tmp_path: Path) -> None:
    rendered = render_agent(_agent(tmp_path), "pi")

    assert rendered.startswith(
        "---\nname: reviewer\ndescription: Reviews a diff for defects.\nthinking: high\n---\n"
    )


def test_inherit_alone_is_valid_and_writes_no_model(tmp_path: Path) -> None:
    agent = _agent(tmp_path, "---\ndescription: D.\nmodel: inherit\n---\nBody.\n")

    assert agent.models == {}
    assert render_agent(agent, "droid").startswith("---\nname: reviewer\ndescription: D.\n---\n")


def test_one_model_for_every_harness_is_refused(tmp_path: Path) -> None:
    with pytest.raises(LoadoutError, match="per-harness map"):
        _agent(tmp_path, "---\ndescription: D.\nmodel: sonnet\n---\nBody.\n")


def test_an_opencode_model_without_a_provider_is_refused(tmp_path: Path) -> None:
    text = "---\ndescription: D.\nmodel:\n  opencode: sonnet\n---\nBody.\n"

    with pytest.raises(LoadoutError, match="provider/model-id"):
        _agent(tmp_path, text)


def test_a_name_differing_from_the_file_is_refused(tmp_path: Path) -> None:
    with pytest.raises(LoadoutError, match="differs from the file name"):
        _agent(tmp_path, "---\nname: other\ndescription: D.\n---\nBody.\n")


@pytest.mark.parametrize(
    ("effort", "harness", "written"),
    [
        ("high", "claude", "high"),
        ("off", "codex", "none"),
        ("xhigh", "droid", "high"),
        ("minimal", "pi", "minimal"),
        ("max", "pi", "max"),
    ],
)
def test_effort_is_translated_to_each_harness(
    tmp_path: Path, effort: str, harness: str, written: str
) -> None:
    agent = _agent(tmp_path, f"---\ndescription: D.\neffort: {effort}\n---\nBody.\n")

    assert effort_for(agent, harness)[0] == written


def test_a_missing_level_takes_the_nearest_lower_one_with_a_note(tmp_path: Path) -> None:
    agent = _agent(tmp_path, "---\ndescription: D.\neffort: max\n---\nBody.\n")

    assert agent_notes(agent, ("claude", "droid")) == (
        (
            "droid",
            (
                "agent 'reviewer': droid has no effort 'max', so 'high', the nearest lower "
                "level, is written"
            ),
        ),
    )


def test_no_lower_level_writes_none_with_a_note(tmp_path: Path) -> None:
    agent = _agent(tmp_path, "---\ndescription: D.\neffort: minimal\n---\nBody.\n")

    assert effort_for(agent, "claude") == (
        None,
        (
            "agent 'reviewer': claude has no effort level at or below 'minimal', so none is "
            "written and it inherits"
        ),
    )


def test_opencode_omits_effort_with_a_note(tmp_path: Path) -> None:
    agent = _agent(tmp_path, "---\ndescription: D.\neffort: high\n---\nBody.\n")

    assert effort_for(agent, "opencode") == (
        None,
        (
            "agent 'reviewer': OpenCode agents have no effort field, so effort 'high' is not "
            "written for OpenCode"
        ),
    )


def test_a_per_harness_effort_map_is_written_verbatim(tmp_path: Path) -> None:
    text = "---\ndescription: D.\neffort:\n  codex: ultra\n  claude: max\n---\nBody.\n"
    agent = _agent(tmp_path, text)

    assert [effort_for(agent, h)[0] for h in ("codex", "claude", "pi")] == [
        "ultra",
        "max",
        None,
    ]


@pytest.mark.parametrize("harness", sorted(KNOWN_HARNESSES))
def test_every_rendered_agent_reads_back_as_its_source(tmp_path: Path, harness: str) -> None:
    agent = _agent(tmp_path)
    expected_effort, _ = effort_for(agent, harness)

    native = extract_agent(harness, render_agent(agent, harness), agent.name)

    assert native.name == agent.name
    assert native.description == agent.description
    assert native.model == agent.models.get(harness)
    assert native.effort == ("off" if expected_effort == "none" else expected_effort)
    assert native.extra == agent.extra.get(harness, ())
    assert native.body.strip() == render_agent_body(agent, harness)


def render_agent_body(agent: Agent, harness: str) -> str:
    return apply_body(agent.body, harness, agent.name).strip()


def test_a_hand_written_codex_agent_with_a_table_cannot_be_read(tmp_path: Path) -> None:
    text = (
        'name = "r"\ndescription = "D."\ndeveloper_instructions = "x"\n'
        '[mcp_servers.docs]\ncommand = "docs"\n'
    )

    with pytest.raises(LoadoutError, match="cannot carry"):
        extract_agent("codex", text, "r")
