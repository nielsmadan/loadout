"""Droid files are written in Droid's own form, so Droid rewriting its droids folder changes nothing.

Creating a droid in Droid 1.2.0's `/droids` rewrites every other droid in that folder whose bytes
differ from Droid's own form. A loadout droid came back unquoted, without its blank line and final
newline, and then read as hand-edited (QA E-1).

Two fixtures pin the form. `golden.json` is js-yaml 4.3.2's `dump` with Droid's options, the port's
reference over 94 cases. `captured-droid-1.2.0.json` is what Droid 1.2.0 itself wrote, captured
black-box. To recheck a new Droid, run `recapture.py` through it and see what differs.
"""

from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

import pytest

import loadout
from loadout.droid_form import document
from loadout.errors import LoadoutError
from loadout.subagents import parse_agent, render_agent

FIXTURES = Path(__file__).parent / "fixtures" / "droid_form"
GOLDEN = json.loads((FIXTURES / "golden.json").read_text())
CAPTURED = json.loads((FIXTURES / "captured-droid-1.2.0.json").read_text(encoding="utf-8"))["files"]
FIELDS = {case["case"]: case["fields"] for case in GOLDEN["cases"]}
# The old form wrote these models unquoted, as a YAML number and as invalid YAML, so Droid
# could not read the rest of the droid back.
OLD_FORM_UNREADABLE = frozenset({"ii-32.md", "ii-33.md"})

SOURCES = {
    "reviewer": (
        '---\ndescription: "Reviews a diff for defects before it is committed."\neffort: high\n'
        "---\n\nReview the staged diff. Report each defect with its file and line.\n"
    ),
    "null": '---\ndescription: "null"\nmodel:\n  droid: "1.5"\n---\n\nBody.\n',
    "yes": (
        '---\ndescription: "Two lines.\\nSecond."\nmodel:\n  droid: "custom: model"\ndroid:\n'
        '  tools: ["Read", "Grep"]\n  mcpServers:\n    - docs\n    - "1"\n  version: "1"\n'
        "---\nBody right after the frontmatter.\n"
    ),
    "listed": (
        '---\ndescription: "Reviews: \\u00a0diffs # 1"\ndroid:\n  tools:\n    - Read\n'
        "  mcpServers: docs, web\n---\n\nTrailing blank lines.\n\n\n"
    ),
}


def _render(tmp_path: Path, name: str, text: str) -> str:
    path = tmp_path / "agents" / f"{name}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return render_agent(parse_agent(path), "droid")


def source(fields: dict) -> str:
    """The source agent whose droid render carries these fields."""
    lines = [f"description: {json.dumps(fields['description'], ensure_ascii=False)}"]
    if "model" in fields:
        lines.append(f"model:\n  droid: {json.dumps(fields['model'], ensure_ascii=False)}")
    if "reasoningEffort" in fields:
        lines.append(f"effort: {fields['reasoningEffort']}")
    block = []
    if "tools" in fields:
        block.append(f"tools: {fields['tools']}")
    if "mcpServers" in fields:
        items = [f"  - {json.dumps(item)}" for item in fields["mcpServers"]]
        block += ["mcpServers:", *items] if items else ["mcpServers: []"]
    if "version" in fields:
        block.append(f"version: {json.dumps(fields['version'])}")
    if block:
        lines += ["droid:", *(f"  {line}" for line in block)]
    return "---\n" + "\n".join(lines) + "\n---\n\nReview the staged diff.\n"


@pytest.mark.parametrize("case", GOLDEN["cases"], ids=lambda case: case["case"])
def test_the_port_writes_what_js_yaml_dumps(case: dict) -> None:
    assert document(case["fields"], GOLDEN["body"]) == case["droid"]


@pytest.mark.parametrize("name", sorted(set(CAPTURED) - OLD_FORM_UNREADABLE))
def test_loadouts_droid_file_is_what_droid_1_2_0_writes(tmp_path: Path, name: str) -> None:
    entry = CAPTURED[name]

    assert (
        _render(tmp_path, name.removesuffix(".md"), source(FIELDS[entry["case"]]))
        == (entry["after"])
    )


@pytest.mark.parametrize("name", sorted(n for n in CAPTURED if n.startswith("i-")))
def test_droid_1_2_0_left_every_droid_in_loadouts_form_as_it_was(name: str) -> None:
    assert CAPTURED[name]["after"] == CAPTURED[name]["before"]


def test_a_name_or_model_that_reads_as_another_type_is_quoted(tmp_path: Path) -> None:
    """Unquoted, `name: null` and `model: 1.5` failed Droid's schema, which then dropped the
    description and model of the droid altogether."""
    assert _render(tmp_path, "null", SOURCES["null"]) == (
        '---\nname: "null"\ndescription: "null"\nmodel: "1.5"\n---\n'
        "<!-- Generated by loadout from agents/null.md. Edits here are replaced on the next "
        "sync. -->\n\nBody."
    )


def test_the_droid_block_renders_as_droid_rewrites_it(tmp_path: Path) -> None:
    assert _render(tmp_path, "yes", SOURCES["yes"]).split("---\n")[1] == (
        'name: "yes"\ndescription: |-\n  Two lines.\n  Second.\nmodel: "custom: model"\n'
        'tools: Read, Grep\nmcpServers:\n  - docs\n  - "1"\nversion: "1"\n'
    )
    assert _render(tmp_path, "listed", SOURCES["listed"]).split("---\n")[1] == (
        'name: listed\ndescription: "Reviews: \\_diffs # 1"\ntools: Read\n'
        "mcpServers:\n  - docs\n  - web\n"
    )


@pytest.mark.parametrize(
    ("block", "message"),
    [
        (
            "droid:\n  color: blue",
            (
                "droid.color is a key Droid ignores and drops when it rewrites its droids "
                "folder; remove it from the droid block"
            ),
        ),
        ("droid:\n  createdAt: x", "droid.createdAt is a key Droid ignores"),
        ("droid:\n  updatedAt: x", "droid.updatedAt is a key Droid ignores"),
        ("droid:\n  reasoningEffort: high", "droid.reasoningEffort is written from effort"),
        ("droid:\n  tools: []", "droid.tools is empty, and Droid drops an empty tools on rewrite"),
        ('droid:\n  version: ""', "droid.version is empty"),
    ],
)
def test_a_droid_block_droid_would_change_is_refused_when_the_agent_is_read(
    tmp_path: Path, block: str, message: str
) -> None:
    path = tmp_path / "r.md"
    path.write_text(f"---\ndescription: D.\n{block}\n---\nB.\n")

    with pytest.raises(LoadoutError, match="^" + re.escape(f"agents/r.md: {message}")):
        parse_agent(path)


@pytest.mark.parametrize(
    "description", ["a\\n\\nb", "a\\n   \\nb", " a\\nb", "a\\nb\\n\\n"], ids=repr
)
def test_a_multiline_value_droid_writes_unreadably_is_refused(
    tmp_path: Path, description: str
) -> None:
    with pytest.raises(LoadoutError, match=r"^agents/r\.md: description holds a blank line"):
        _render(tmp_path, "r", f'---\ndescription: "{description}"\n---\nB.\n')


@pytest.mark.migration_integration
def test_init_drops_a_key_droid_ignores_with_a_note(tmp_path: Path, capsys) -> None:
    root = tmp_path / "p"
    droid = root / ".factory" / "droids" / "reviewer.md"
    droid.parent.mkdir(parents=True)
    droid.write_text(
        "---\nname: reviewer\ndescription: Reviews.\ncolor: blue\ncreatedAt: 2026-11-01\n"
        "tools: Read, Grep\n---\nReview the diff.\n"
    )
    subprocess.run(["git", "init", "-q", str(root)], check=True)

    argv = ["init", "project", "--root", str(root), "--harness", "droid"]
    assert loadout.main([*argv, "--dry-run", "--json"]) == 0
    notes = json.loads(capsys.readouterr().out)["notes"]
    assert loadout.main([*argv, "--yes"]) == 0

    assert [note for note in notes if "ignored by Droid" in note] == [
        f"{droid}: color is ignored by Droid and was not carried",
        f"{droid}: createdAt is ignored by Droid and was not carried",
    ]
    assert (root / "loadout" / "agents" / "reviewer.md").read_text() == (
        '---\ndescription: "Reviews."\ndroid:\n  tools: Read, Grep\n---\nReview the diff.\n'
    )
