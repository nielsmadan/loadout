"""ADR 0013 for droid files: Droid's form, which loadout now writes, reads back into the source.

`render(extract(x)) == x` byte for byte, over droid files holding every shape the renderer emits.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from loadout.subagents import extract_agent, parse_agent, render_agent, source_agent
from test_droid_form import CAPTURED, FIELDS, GOLDEN, OLD_FORM_UNREADABLE, SOURCES


@pytest.mark.parametrize("name", sorted(SOURCES))
def test_a_droid_file_reads_back_to_a_source_that_renders_it_again(
    tmp_path: Path, name: str
) -> None:
    first = tmp_path / "first" / f"{name}.md"
    first.parent.mkdir()
    first.write_text(SOURCES[name])
    rendered = render_agent(parse_agent(first), "droid")

    native = extract_agent("droid", rendered, name)
    second = tmp_path / "second" / f"{name}.md"
    second.parent.mkdir()
    second.write_text(source_agent([("droid", native)]))

    assert render_agent(parse_agent(second), "droid") == rendered
    assert native.body.endswith("\n")


def test_a_droid_file_from_before_droids_form_still_reads_back(tmp_path: Path) -> None:
    """The blank line and final newline loadout wrote until now come back as the same body."""
    banner = (
        "<!-- Generated by loadout from agents/r.md. Edits here are replaced on the next sync. -->"
    )
    old = f'---\nname: r\ndescription: "D."\n---\n\n{banner}\n\nBody.\n'
    new = f"---\nname: r\ndescription: D.\n---\n{banner}\n\nBody."

    assert extract_agent("droid", old, "r").body == extract_agent("droid", new, "r").body


@pytest.mark.parametrize("case", GOLDEN["cases"], ids=lambda case: case["case"])
def test_every_file_droid_writes_reads_back_to_its_fields(case: dict) -> None:
    """The golden bytes come from Droid's own dumper, so this reads every escape and style it
    writes, not only the ones loadout's renderer happens to produce."""
    native = extract_agent("droid", case["droid"], case["case"])
    fields = case["fields"]

    assert (native.name, native.description, native.model, native.effort) == (
        fields["name"],
        fields["description"],
        fields.get("model"),
        fields.get("reasoningEffort"),
    )


@pytest.mark.parametrize("name", sorted(set(CAPTURED) - OLD_FORM_UNREADABLE))
def test_what_droid_1_2_0_wrote_reads_back_and_renders_again(tmp_path: Path, name: str) -> None:
    written = CAPTURED[name]["after"]
    fields = FIELDS[CAPTURED[name]["case"]]
    native = extract_agent("droid", written, name.removesuffix(".md"))
    source = tmp_path / name
    source.write_text(source_agent([("droid", native)]), encoding="utf-8")

    assert (native.description, native.model, native.effort) == (
        fields["description"],
        fields.get("model"),
        fields.get("reasoningEffort"),
    )
    assert render_agent(parse_agent(source), "droid") == written
