from __future__ import annotations

import json
from pathlib import Path

import pytest

import loadout
from loadout.machine import machine_config_path

pytestmark = pytest.mark.migration_integration

UNMANAGED = (
    "commands/foo.md",
    "commands/nested/bar.md",
    "projects/p1/log.jsonl",
    ".credentials.json",
    ".DS_Store",
    "ide/1.lock",
    "notes.txt",
    "mystery/deep/x.md",
)


def _dotfiles(root: Path) -> Path:
    claude = root / "dotfiles" / "claude"
    files = {
        "CLAUDE.md": "# Me\n\nBe brief.\n",
        "settings.json": '{"permissions": {"allow": ["Bash(git status)"]}}\n',
        "skills/review/SKILL.md": "---\nname: review\ndescription: r\n---\nReview it.\n",
        "commands/foo.md": "Do foo.\n",
        "commands/nested/bar.md": "Do bar.\n",
        "agents/helper.md": "---\nname: helper\ndescription: h\n---\nHelp.\n",
        "projects/p1/log.jsonl": '{"m": 1}\n',
        ".credentials.json": '{"token": "opaque"}\n',
        ".DS_Store": "\x00\x01finder",
        "ide/1.lock": '{"pid": 1}\n',
        "notes.txt": "scratch\n",
        "mystery/deep/x.md": "unknown\n",
    }
    for relative, content in files.items():
        (claude / relative).parent.mkdir(parents=True, exist_ok=True)
        (claude / relative).write_text(content)
    return claude


def _snapshot(root: Path) -> dict[str, bytes | str]:
    return {
        path.relative_to(root).as_posix(): "link"
        if path.is_symlink()
        else "dir"
        if path.is_dir()
        else path.read_bytes()
        for path in root.rglob("*")
    }


def _link_per_file(dotfiles: Path, claude: Path) -> None:
    (claude / "skills").mkdir(parents=True)
    for entry in dotfiles.iterdir():
        if entry.name != "skills":
            (claude / entry.name).symlink_to(entry)
    (claude / "skills" / "review").symlink_to(dotfiles / "skills" / "review")


def _init(source: Path, *extra: str) -> int:
    source.mkdir(exist_ok=True)
    return loadout.main(["init", "global", str(source), "--harness", "claude", *extra])


def _assert_adopted(claude: Path, dotfiles: Path) -> None:
    for output in ("CLAUDE.md", "settings.json", "skills/review/SKILL.md", "agents/helper.md"):
        assert (claude / output).is_file()
        assert not (claude / output).is_symlink()
        assert (claude / output).resolve() == claude / output
    assert (claude / "CLAUDE.md").read_text().endswith("# Me\n\nBe brief.\n")
    assert "Generated by loadout" in (claude / "CLAUDE.md").read_text()
    settings = json.loads((claude / "settings.json").read_text())
    assert settings["permissions"]["allow"] == ["Bash(git status)"]
    for entry in UNMANAGED:
        assert (claude / entry).resolve() == dotfiles / entry
        assert (claude / entry).read_bytes() == (dotfiles / entry).read_bytes()


def test_a_symlinked_claude_directory_is_adopted_by_de_linking(
    tmp_path: Path, fake_home: Path, capsys
) -> None:
    dotfiles = _dotfiles(tmp_path)
    claude = fake_home / ".claude"
    claude.symlink_to(dotfiles, target_is_directory=True)
    before = _snapshot(dotfiles)
    source = tmp_path / "src"

    assert _init(source, "--dry-run", "--json") == 0
    preview = json.loads(capsys.readouterr().out)
    assert preview["delinked"] == [
        {
            "link": str(claude),
            "target": str(dotfiles),
            "directory": True,
            "superseded": [
                str(dotfiles / "CLAUDE.md"),
                str(dotfiles / "agents/helper.md"),
                str(dotfiles / "settings.json"),
                str(dotfiles / "skills/review/SKILL.md"),
            ],
        }
    ]
    assert claude.is_symlink()

    assert _init(source, "--yes") == 0

    out = capsys.readouterr().out
    assert (
        f"{claude} was a symlink into {dotfiles}. Loadout's files are now real files here; "
        f"everything else still links into {dotfiles}. {dotfiles}'s copies of CLAUDE.md, "
        "agents/helper.md, settings.json, skills/review/SKILL.md are no longer used. Entries "
        f"added later to {dotfiles}'s top level, or inside agents/, skills/, will not appear here."
    ) in out
    assert not claude.is_symlink()
    _assert_adopted(claude, dotfiles)
    assert _snapshot(dotfiles) == before
    assert loadout.main(["sync", "--global"]) == 0
    assert "Up to date." in capsys.readouterr().out
    assert (claude / "commands").readlink() == dotfiles / "commands"
    (dotfiles / "commands/later.md").write_text("Later.\n")
    assert (claude / "commands/later.md").read_text() == "Later.\n"
    (dotfiles / "later.md").write_text("Top.\n")
    (dotfiles / "skills/added/SKILL.md").parent.mkdir()
    (dotfiles / "skills/added/SKILL.md").write_text("Added.\n")
    assert not (claude / "later.md").exists()
    assert sorted(p.name for p in (claude / "skills").iterdir()) == ["review"]


def test_stow_style_per_file_links_are_adopted_by_de_linking(
    tmp_path: Path, fake_home: Path, capsys
) -> None:
    dotfiles = _dotfiles(tmp_path)
    claude = fake_home / ".claude"
    _link_per_file(dotfiles, claude)
    before = _snapshot(dotfiles)

    assert _init(tmp_path / "src", "--yes") == 0

    out = capsys.readouterr().out
    assert (
        f"{claude / 'settings.json'} was a symlink to {dotfiles / 'settings.json'}. It is now a "
        f"real file written by loadout; {dotfiles / 'settings.json'} is no longer used."
    ) in out
    assert (
        f"{claude / 'skills/review'} was a symlink into {dotfiles / 'skills/review'}. Loadout's "
        f"files are now real files here; everything else still links into "
        f"{dotfiles / 'skills/review'}. {dotfiles / 'skills/review'}'s copies of SKILL.md are no "
        f"longer used. Entries added later to {dotfiles / 'skills/review'}'s top level will not "
        "appear here."
    ) in out
    _assert_adopted(claude, dotfiles)
    for unmanaged in ("commands", "projects", ".credentials.json"):
        assert (claude / unmanaged).is_symlink()
    assert _snapshot(dotfiles) == before
    assert loadout.main(["sync", "--global"]) == 0
    assert "Up to date." in capsys.readouterr().out


def test_a_home_under_a_symlinked_prefix_is_canonicalised_not_de_linked(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys
) -> None:
    """The macOS /tmp case: HOME and the machine config sit under a linked prefix."""
    real = tmp_path / "real"
    (real / "home").mkdir(parents=True)
    alias = tmp_path / "alias"
    alias.symlink_to(real, target_is_directory=True)
    monkeypatch.setenv("HOME", str(alias / "home"))
    dotfiles = _dotfiles(tmp_path)
    (alias / "home" / ".claude").symlink_to(dotfiles, target_is_directory=True)
    before = _snapshot(dotfiles)

    assert _init(alias / "src", "--yes") == 0

    assert alias.readlink() == real
    assert sorted(p.name for p in tmp_path.iterdir()) == ["alias", "dotfiles", "real"]
    _assert_adopted(real / "home" / ".claude", dotfiles)
    assert machine_config_path().resolve() == real / "home/.config/loadout/config.toml"
    assert _snapshot(dotfiles) == before
    capsys.readouterr()
    assert loadout.main(["sync", "--global"]) == 0
    assert "Up to date." in capsys.readouterr().out


def test_a_link_above_a_harness_root_is_kept_and_written_through(
    tmp_path: Path, fake_home: Path, capsys
) -> None:
    """~/.config is not OpenCode's root; ~/.config/opencode is. Only links at or below
    a harness root are deployment links, so ~/.config stays a link."""
    config = tmp_path / "dotfiles" / "config"
    (config / "opencode").mkdir(parents=True)
    (config / "opencode" / "AGENTS.md").write_text("# oc\n")
    (config / "other").mkdir()
    (config / "other" / "keep.txt").write_text("kept\n")
    (fake_home / ".config").symlink_to(config, target_is_directory=True)
    source = tmp_path / "src"
    source.mkdir()

    init = ["init", "global", str(source), "--harness", "opencode", "--yes"]
    assert loadout.main(init) == 0

    notice = (
        f"{fake_home / '.config'} is a symlink to {config}; loadout writes through it, so the "
        f"files it writes under {fake_home / '.config'} land in {config}."
    )
    assert capsys.readouterr().out.count(notice) == 1
    assert (fake_home / ".config").readlink() == config
    assert (config / "loadout" / "config.toml").is_file()
    assert "Generated by loadout" in (config / "opencode" / "AGENTS.md").read_text()
    assert (config / "other" / "keep.txt").read_text() == "kept\n"


def test_a_symlink_cycle_under_a_harness_root_is_still_refused(
    tmp_path: Path, fake_home: Path, capsys
) -> None:
    claude = fake_home / ".claude"
    (claude / "skills").mkdir(parents=True)
    (claude / "CLAUDE.md").write_text("# Me\n")
    (claude / "skills" / "loop").symlink_to(claude, target_is_directory=True)

    assert _init(tmp_path / "src", "--yes") == 2

    assert f"symlink-cycle: Resolve the cyclic directory mapping.\n  {claude}/skills/loop" in (
        capsys.readouterr().err
    )
    assert (claude / "skills" / "loop").is_symlink()
